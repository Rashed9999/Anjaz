#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
#  AMIAL-DB-UP-001 — قاعدةُ البيانات تنهض قبل من يحتاجها.
# ══════════════════════════════════════════════════════════════════════
#  **العطل المقيس:** سقطت البوّابةُ ثلاثَ مرّاتٍ في جلسةٍ واحدة بـ٢١٧٣
#  اختباراً «فاشلاً» من ٢٤٠٠. والسببُ ليس شيفرةً مكسورة:
#
#      إقلاعُ الحاوية : 2026-08-15 01:48:42
#      وقبله بساعاتٍ  : خمسةُ التزاماتٍ بين 20:56 و 00:22
#
#  **فالحاويةُ تُستأنف من جديد، والآلةُ كلُّها تذهب وتعود** — لا مقبسَ ولا
#  خادمَ ولا حارسَه. ولذلك لم يترك الموتُ أثراً في أيّ سجلّ، ولذلك ذهب
#  `mariadbd-safe` مع `mariadbd` (وهو الذي يُعيده عند الانهيار)، ولذلك
#  كانت الذاكرةُ ١٣ جيجا حرّةً ولا OOM.
#
#  **والحلقةُ المفقودة:** `.claude/hooks/session-start.sh` مبنيٌّ ليُعيدها
#  بعد الإقلاع — **ولا يُطلَق في هذه البيئة**: `CLAUDE_PROJECT_DIR` غيرُ
#  مضبوطٍ أصلاً، وجذرُ المشروع `/home/user` لا `/home/user/Anjaz`، فلا
#  تُقرأ `Anjaz/.claude/settings.json`. (وهو نفسُ ما وقع لفهرس المهارات.)
#
#  فمن يحتاجُها يُنهضها بنفسه، ولا يعتمد على خطّافٍ لا يُطلَق.
#
#  **ولا يُخفي الفشل:** إن لم تنهض يخرج بـ1 ورسالةٍ تقول ما وقع — فتقريرُ
#  «٢١٧٣ اختباراً فشل» يُرسل من يقرؤه خلف عطلٍ لا وجودَ له. (القاعدة
#  السابعة: «غير معروف» ليس صفراً — وهنا: «القاعدةُ ساقطة» ليست
#  «٢١٧٣ عطلاً».)
# ══════════════════════════════════════════════════════════════════════

set -uo pipefail

WAIT=${1:-45}

alive() { mariadb -uroot -e 'SELECT 1' >/dev/null 2>&1; }

alive && exit 0

if ! command -v mariadbd-safe >/dev/null 2>&1; then
    echo "✗ mariadbd-safe غير مثبَّت — لا يمكن إنهاضُ قاعدة البيانات." >&2
    exit 1
fi

echo "⏳ قاعدةُ البيانات ساقطة (الحاويةُ أُعيد إقلاعُها؟) — تُنهَض…" >&2

mkdir -p /run/mysqld /var/log/mysql 2>/dev/null || true
chown mysql:mysql /run/mysqld /var/log/mysql 2>/dev/null || true

# ── قناةُ الأثر تُعاد نصبُها ─────────────────────────────────────────
#
# `/etc/mysql` خارجُ المستودع، فيذهب مع الحاوية. والنسخةُ المرجعيّة في
# المستودع، وتُنصَب هنا قبل الإقلاع — لا بعده: `log_error` لا يُقرأ إلّا
# عند بدء الخادم. **وبلا هذا يبقى الموتُ بلا أثرٍ كما كان.**
CONF=/etc/mysql/mariadb.conf.d/99-amial-forensics.cnf
SRC="$(dirname "${BASH_SOURCE[0]}")/db-forensics.cnf"

if [[ -d /etc/mysql/mariadb.conf.d && -f "$SRC" ]] && ! cmp -s "$SRC" "$CONF"; then
    cp "$SRC" "$CONF" 2>/dev/null && echo "  · أُعيد نصبُ قناة الأثر." >&2
fi

# `setsid` تمنحها جلسةً ومجموعةَ عمليّاتٍ خاصّتَين بها بدل وراثة جلسةِ
# النداء الذي أطلقها. وهذا **ليس علاجَ العطل أعلاه** — الحاويةُ تأخذ
# الجميع معها — لكنّه يمنع صنفاً آخر: كنسَ مجموعةِ نداءٍ منتهٍ.
setsid mariadbd-safe --user=mysql >/dev/null 2>&1 </dev/null &

for _ in $(seq 1 "$WAIT"); do
    alive && { echo "✓ قاعدةُ البيانات جاهزة." >&2; exit 0; }
    sleep 1
done

echo "✗ لم تنهض قاعدةُ البيانات خلال ${WAIT} ثانية." >&2
echo "  آخرُ ما في السجلّ:" >&2
tail -5 /var/log/mysql/error.log 2>/dev/null | sed 's/^/    /' >&2 \
    || echo "    (لا سجلّ — راجع /etc/mysql/mariadb.conf.d/99-amial-forensics.cnf)" >&2

exit 1
