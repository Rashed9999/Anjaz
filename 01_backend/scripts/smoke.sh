#!/usr/bin/env bash
#
# AMIAL-PROD-READINESS-006 — **فحصُ دخانٍ بعد النشر.**
#
# ══════════════════════════════════════════════════════════════════════
# **الثمن — قِيس في تدقيق الجاهزيّة:**
#
#   $ grep -inE 'rollback|smoke' docs/DEPLOYMENT_GUIDE.md
#   (صفرُ نتائج)
#
# بعد كلّ نشرةٍ لا يُفحَص شيء. ولوحةُ Coolify تقول `Running (no health
# check)` — فحتّى إقلاعُ الحاوية لا يُتحقَّق منه.
#
# **ولا يُغني `scripts/sweep-admin.php` عنه**: ذاك يُقلع التطبيقَ **داخل
# العمليّة** ويفتح المسارات بالنواة مباشرةً. فهو يفحص **الشيفرة**، وهذا
# يفحص **الخادمَ المنشور**: الشهادةَ، والوسيط، وnginx، وphp-fpm،
# والقاعدةَ، والبيئةَ — أي كلَّ ما لا تراه شيفرةٌ سليمة.
#
# ══════════════════════════════════════════════════════════════════════
# **الاستعمال — من طرفيّة Coolify بعد النشر:**
#
#     bash scripts/smoke.sh
#     bash scripts/smoke.sh https://amialpay.com
#
# ويخرج بصفرٍ إن سلمت كلُّ الفحوص، وبواحدٍ إن سقط منها شيء — فيصلح
# لخطوةٍ آليّةٍ بعد النشر.
set -uo pipefail

BASE="${1:-${AMIAL_SMOKE_BASE:-https://amialpay.com}}"
BASE="${BASE%/}"

PASS=0; FAIL=0
ok()  { printf '  \033[32m✓\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad() { printf '  \033[31m✗\033[0m %s\n' "$1"; FAIL=$((FAIL+1)); }

# يُعيد "رمز|زمن" — والزمنُ يُقال لأنّ بطئاً شديداً عطلٌ ولو ردّ ٢٠٠.
probe() {
  curl -sS -o /tmp/amial_smoke_body -w '%{http_code}|%{time_total}' \
       --max-time 20 "$1" 2>/dev/null || echo "000|0"
}

printf '\n\033[1mفحصُ الدخان — %s\033[0m\n' "$BASE"
printf '%s\n' "──────────────────────────────────────────────"

# ── ① جاهزيّةُ النسخة ─────────────────────────────────────────────────
# **أوّلاً وقبل كلّ شيء**: هذه وحدَها تفحص القاعدةَ والتخزينَ بالعمل.
R=$(probe "$BASE/railway-health"); CODE="${R%%|*}"; T="${R##*|}"
if [[ "$CODE" == "200" ]]; then
  STATE=$(grep -o '"status":"[a-z_]*"' /tmp/amial_smoke_body | head -1 | cut -d'"' -f4)
  if [[ "$STATE" == "warming" ]]; then
    bad "الجاهزيّة: ما تزال في نافذة الإقلاع (warming) — أعِد الفحصَ بعد دقيقتين"
  else
    ok "الجاهزيّة: القاعدةُ والتخزينُ والطابور (${T}s)"
  fi
elif [[ "$CODE" == "503" ]]; then
  bad "الجاهزيّة: ٥٠٣ — قطعةٌ ساقطة. افتح اللوحة ← صحّة النظام"
  head -c 400 /tmp/amial_smoke_body | sed 's/^/      /'
else
  bad "الجاهزيّة: رمز ${CODE} — لا يجيب التطبيقُ أصلاً"
fi

# ── ② نقطةُ الرصد الخارجيّة ───────────────────────────────────────────
R=$(probe "$BASE/api/v1/amial/ping"); CODE="${R%%|*}"
[[ "$CODE" == "200" ]] && ok "نقطةُ الرصد /ping" || bad "نقطةُ الرصد: رمز ${CODE}"

# ── ③ بابُ الإدارة يُفتح ──────────────────────────────────────────────
# **يُفحص أنّه يُعرض لا أنّه يقبل الدخول** — لا كلمةَ مرورٍ في سكربت.
R=$(probe "$BASE/admin/auth/login"); CODE="${R%%|*}"
# والرمزُ يُقبل بصيغتيه: وسمُ `meta[csrf-token]` الذي يقرؤه الجافاسكربت،
# أو `input[name=_token]` في النموذج. وسقط هذا الفحصُ في أوّل تشغيلٍ
# لأنّه طلب الأولى وحدَها والصفحةُ تحمل الثانية.
if [[ "$CODE" == "200" ]] && grep -qE 'csrf-token|name="_token"' /tmp/amial_smoke_body; then
  ok "بابُ الإدارة يُعرض ومعه رمزُ CSRF"
else
  bad "بابُ الإدارة: رمز ${CODE} — أو بلا رمز CSRF (حلقةُ ٤١٩ تعود)"
fi

# ── ④ الواجهةُ العامّة ────────────────────────────────────────────────
R=$(probe "$BASE/"); CODE="${R%%|*}"
[[ "$CODE" == "200" ]] && ok "الصفحةُ الرئيسة" || bad "الصفحةُ الرئيسة: رمز ${CODE}"

# ── ⑤ ترويساتُ الأمان ────────────────────────────────────────────────
H=$(curl -sSI --max-time 20 "$BASE/" 2>/dev/null || true)
# **وHSTS تُطلَب على HTTPS وحدَها.** إرسالُها على HTTP بلا معنىً،
# و`SecurityHeaders` لا يضيفها عمداً — فطلبُها هنا يجعل الفحصَ يسقط على
# تشغيلٍ محلّيٍّ سليم، وحارسٌ يمنع الصوابَ يُنزَع بعد يومين.
NEEDED=("X-Frame-Options" "X-Content-Type-Options" "Content-Security-Policy")
[[ "$BASE" == https://* ]] && NEEDED+=("Strict-Transport-Security")

MISS=""
for h in "${NEEDED[@]}"; do
  grep -qi "^${h}:" <<<"$H" || MISS="${MISS} ${h}"
done
[[ -z "$MISS" ]] && ok "ترويساتُ الأمان (${#NEEDED[@]})" || bad "ترويساتٌ ناقصة:${MISS}"

# ── ⑥ معرِّفُ الطلب ───────────────────────────────────────────────────
# بدونه لا يُربط عطلٌ يشتكي منه تاجرٌ بسطرٍ في السجلّ.
grep -qi '^x-request-id:' <<<"$H" \
  && ok "معرِّفُ الطلب يُعاد إلى العميل" \
  || bad "لا معرِّفَ طلبٍ في الردّ — الشكوى لا تُربَط بسجلّ"

# ── ⑦ لا يُفشي التنقيحُ شيئاً ────────────────────────────────────────
# **الفحصُ الأهمُّ أمنيّاً**: صفحةُ ٥٠٠ في وضع التنقيح تعرض المسارات
# والاستعلامات. فيُطلب مسارٌ لا وجود له ويُقرأ ما يعود.
R=$(probe "$BASE/__amial_smoke_no_such_path__"); CODE="${R%%|*}"
if grep -qiE 'Whoops|stack trace|vendor/laravel|APP_KEY|DB_PASSWORD' /tmp/amial_smoke_body; then
  bad "⚠ التنقيحُ مفتوح — الصفحةُ تُفشي مساراتٍ أو أسراراً. اضبط APP_DEBUG=false فوراً"
else
  ok "صفحةُ الخطأ لا تُفشي شيئاً (رمز ${CODE})"
fi

rm -f /tmp/amial_smoke_body

printf '%s\n' "──────────────────────────────────────────────"
if [[ $FAIL -eq 0 ]]; then
  printf '\033[32m  نجح %d فحصاً · النشرةُ سليمة\033[0m\n\n' "$PASS"
  exit 0
fi
printf '\033[31m  فشل %d فحصاً (ونجح %d)\033[0m\n' "$FAIL" "$PASS"
printf '  النشرةُ لا تُعتمد قبل أن يصير الفشلُ صفراً.\n\n'
exit 1
