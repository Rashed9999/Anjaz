<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * AMIAL-WIZARD-HONESTY-001 — **مرشدٌ يطلب عملاً أدّته الشيفرةُ يُعوّد
 * قارئَه على تخطّي القائمة.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ما قِيس:** `wizard-production-blockers.sh` كان يقول عن فحص الصحّة:
 *
 *     «لا يوجد اليوم»
 *     «الناقصُ أن يُوصَل به — وهو ما لا يفعله إلّا أنت»
 *
 * **وقد صار موجوداً**: `Dockerfile` — الملفُّ الذي يبنيه Coolify فعلاً —
 * يُعلن `HEALTHCHECK` يسأل `/health/readiness`. فالجملتان كانتا صادقتين
 * يومَ كُتبتا وكذبتا بعد الإصلاح.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والثمنُ ليس دقيقتين من وقت صاحب المشروع.** قائمةٌ من عشرٍ فيها
 * بندان مؤدَّيان تُقرأ مرّةً بتمعّن ثمّ تُتخطّى — **فيُتخطّى معها البندُ
 * الذي لا يؤدّيه غيرُ الإنسان**: إثباتُ وصول الإنذار على الهاتف، والنسخةُ
 * خارج الخادم.
 *
 * وهو نمطٌ دفع المشروعُ ثمنَه مرّتين: «كُسرت السلسلة في ٧ مواضع» على
 * صفوفٍ لم يمسَّها أحد، و«٢١٧٣ اختباراً فشل» ولا واحدٌ منها مكسور.
 * **ومُبلِّغٌ يكذب مرّةً يُتجاهَل يومَ يصدق.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولمَ حارسٌ لا تصحيحٌ وحدَه:** المرشدُ نصٌّ يشيخ مع كلّ إصلاح، ولا
 * مُصرِّفَ يقرؤه ولا اختبارَ كان يمسّه. **وملفَّان يتباعدان** هو السببُ
 * المسجَّل في `CLAUDE.md` لثلاثة أعطالٍ سابقة (Dockerfile مقابل
 * Dockerfile.prod مرّتين، ومجلّدات PDF مرّة).
 */
class WizardHonestyGuardTest extends TestCase
{
    private function wizard(): string
    {
        return (string) file_get_contents(base_path('scripts/wizard-production-blockers.sh'));
    }

    /**
     * `Dockerfile` **بلا أسطر تعليقه**.
     *
     * وأوّلُ صياغةٍ لهذا الحارس التقطت كلمةَ `HEALTHCHECK` **داخل التعليق
     * الذي يشرحها** — وهو التعليقُ القائل إنّها كانت في `Dockerfile.prod`
     * وحدَه. فسقط الحارسُ على شيفرةٍ سليمة.
     *
     * **وهو نمطُ العطل المسجَّل في القاعدة الثانية بنصّه**: «حارسٌ مرّ
     * لأنّ الكلمة وردت في تعليقٍ عربيٍّ يشرح أنّ النقطة غير موصولة» —
     * أي أنّ التعليقَ الذي يصف العطلَ كان يُخفيه. وهنا وقع معكوساً:
     * أخفى **الإصلاح**.
     */
    private function dockerfile(): string
    {
        $s = (string) file_get_contents(base_path('Dockerfile'));

        return preg_replace('~^[ \t]*#[^\n]*$~m', '', $s) ?? '';
    }

    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function the_deployed_image_declares_its_own_health_check(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وفي `Dockerfile` لا `Dockerfile.prod`.** Coolify يبني الأوّل،
        // والثاني كان يحمل الفحصَ فلا يحرس شيئاً — وهو مسجَّلٌ في
        // `CLAUDE.md` بعد أن كلّف سقفَ تزامنٍ قدرُه خمسة.
        // ══════════════════════════════════════════════════════════════
        $df = $this->dockerfile();

        $this->assertStringContainsString('HEALTHCHECK', $df,
            'الصورةُ المنشورة بلا فحصِ صحّة — فكلُّ نشرةٍ «ناجحة» مهما كانت الحال');

        $at = (int) strpos($df, 'HEALTHCHECK');

        $this->assertStringContainsString('/health/readiness', substr($df, $at, 400),
            'الفحصُ يسأل مسباراً متسامحاً — ومتسامحٌ لا يصلح حارساً دائماً');
    }

    /** @test */
    public function the_wizard_does_not_claim_a_solved_step_is_missing(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وهذا هو العطلُ بعينه.** الجملتان كانتا صادقتين يومَ كُتبتا؛
        // والإصلاحُ لم يمسّ النصّ، فصار يطلب عملاً مؤدّى.
        // ══════════════════════════════════════════════════════════════
        $w = $this->wizard();

        $this->assertStringNotContainsString('فحصُ صحّة النشر — لا يوجد اليوم', $w,
            'المرشدُ يقول إنّ فحصَ الصحّة غيرُ موجود، والصورةُ تُعلنه');

        $this->assertStringNotContainsString('الناقصُ أن يُوصَل به — وهو ما لا يفعله إلّا أنت', $w,
            'المرشدُ ينسب إلى الإنسان عملاً أدّته الصورة');
    }

    /** @test */
    public function a_step_the_code_enforces_is_not_a_blocking_question(): void
    {
        // **وسؤالٌ حاجزٌ على أمرٍ محروسٍ يُنتج بنداً «مُتخطّىً» في التقرير
        // النهائيّ** — فيقرأ صاحبُ المشروع «تخطّيتَ فحصَ الصحّة» وهو مضبوط،
        // ويذهب يبحث عن عطلٍ لا وجود له. (حارسٌ يكذب أسوأ من غيابه.)
        $w = $this->wizard();

        $at = (int) strpos($w, 'stage "فحصُ صحّة النشر');

        $this->assertNotSame(0, $at, 'اختفت مرحلةُ فحص الصحّة من المرشد');

        $next = preg_match('~\nstage ~', $w, $m, PREG_OFFSET_CAPTURE, $at + 10)
            ? (int) $m[0][1] : strlen($w);

        $this->assertStringNotContainsString('SKIPPED+=(', substr($w, $at, $next - $at),
            'المرحلةُ ما زالت تُسجَّل «مُتخطّاة» عند الرفض — وهي محروسةٌ في الصورة');
    }

    /** @test */
    public function the_debug_stage_still_says_the_boot_guard_enforces_it(): void
    {
        // **والعكسُ يُحرَس أيضاً.** حاجزُ `APP_DEBUG` في `entrypoint.sh`
        // يرفض تقديمَ الخدمة — ومرشدٌ لا يقول ذلك يجعل القارئَ يظنُّ
        // الأمرَ متروكاً لانتباهه.
        $w = $this->wizard();

        $this->assertStringContainsString('لن تُقلع الحاويةُ إن كان APP_DEBUG=true', $w,
            'المرشدُ لا يقول إنّ الحاجزَ مفروضٌ عند الإقلاع');

        $this->assertStringContainsString('AMIAL_ALLOW_DEBUG', $w,
            'المرشدُ لا يذكر منفذَ الخروج المقصود لبيئة التجربة');
    }

    /** @test */
    public function the_irreducible_steps_are_still_asked_for(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **ومرشدٌ يُخفّف نفسَه حتّى يفرغ لا يحرس شيئاً.** خمسٌ لا يؤدّيها
        // إلّا إنسان: ضغطُ النشر، ورقمُ الإنذار، وإثباتُ وصوله على الهاتف،
        // والنسخةُ خارج الخادم، وقياسُ الطاقة. **وهذه لا تُحذف بحال.**
        // ══════════════════════════════════════════════════════════════
        $w = $this->wizard();

        foreach ([
            'اضغط Deploy' => 'ضغطُ النشر — والدفعُ إلى git لا ينشر',
            'AMIAL_RECON_ALERT_TO' => 'قناةُ الإنذار',
            'amial:alert-test' => 'إثباتُ وصول الإنذار على الهاتف',
            'http-load.php' => 'قياسُ الطاقة على الخادم الحقيقيّ',
            'نسخةٌ خارج الخادم' => 'النسخةُ خارج الخادم',
        ] as $needle => $why) {
            $this->assertStringContainsString($needle, $w,
                "سقطت خطوةٌ لا يؤدّيها إلّا إنسان: {$why}");
        }
    }
}
