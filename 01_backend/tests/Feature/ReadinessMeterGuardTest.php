<?php

namespace Tests\Feature;

use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Artisan;
use Tests\TestCase;

/**
 * AMIAL-READINESS-METER-001 — **الجاهزيّةُ رقمٌ يُحسَب لا حكمٌ يُصدَر.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **لماذا وُجد المقياس:**
 *
 * سُئل مراراً «هل نحن جاهزون لألفي مستخدم؟»، وكان الجوابُ في كلّ مرّةٍ
 * فقرةً يكتبها من سُئل. **وحكمٌ يعتمد على كاتبه لا يُراجَع ولا يُتابَع**:
 * لا يُعرف متى تغيّر، ولا يُعرف أنّه صار عشرةً إلّا بأن يُسأل من جديد.
 *
 * فصار كلُّ شرطٍ **يُقاس من مصدره**، والرقمُ حاصلَ القياس — يصير عشرةً
 * حين يصير كذلك، لا حين يقتنع أحد.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وأخطرُ ما يُحرَس فيه: ألّا يُقرأ المجهولُ نجاحاً.**
 *
 * ثلاثةٌ لا تُعرف إلّا من الخادم المنشور — أنّ النشرةَ جرت، وأنّ فحصَ
 * الصحّة مضبوطٌ في Coolify، وسقفُ php-fpm الحقيقيّ. **ومقياسٌ يعدّها
 * نجاحاً يُخرج عشرةً على مشروعٍ لم يُنشَر** — وهو الصمتُ بثوب رقم.
 *
 * (القاعدةُ السابعة: الصفرُ يُقرأ «فحصنا فلم نجد»، والغيابُ يُقال بسببه.
 * والقاعدةُ الأولى: «الطبقةُ المُخطّاةُ لا تُعدّ نجاحاً».)
 */
class ReadinessMeterGuardTest extends TestCase
{
    use RefreshDatabase;

    /**
     * **ولا تُسمّى `run`** — فهي نهائيّةٌ في `TestCase`، وتجاوزُها خطأٌ
     * قاتلٌ يُسقط المجموعةَ كلَّها لا هذا الملفَّ وحدَه. (وقع مثلُه في
     * هذه الجلسة على `call()`.)
     */
    private function meter(): string
    {
        Artisan::call('amial:readiness');

        return Artisan::output();
    }

    /**
     * سطورُ الشروط وحدَها — كلُّ سطرٍ `[العلامة, نصُّه]`.
     *
     * **والترويسةُ والخلاصةُ تُستبعدان**، فهما لا يحملان علامة؛ ولولا
     * ذلك لعُدّ «(2 من 10 …)» شرطاً.
     *
     * @return list<array{0:string,1:string}>
     */
    private function rows(string $out): array
    {
        preg_match_all('~^\h{2}([✓✗؟])\h(.*)$~mu', $out, $m, PREG_SET_ORDER);

        $rows = array_map(fn ($r) => [$r[1], trim($r[2])], $m);

        // **ومطابِقٌ عمي يخرج أخضرَ على صفر** — وهو الصمتُ بثوب نجاح.
        $this->assertNotEmpty($rows, 'لم يُلتقَط سطرُ شرطٍ واحد — المطابِقُ لا يقرأ المقياس');

        return $rows;
    }

    /** @return array{'✓':int,'✗':int,'؟':int} */
    private function marks(string $out): array
    {
        $count = ['✓' => 0, '✗' => 0, '؟' => 0];

        foreach ($this->rows($out) as [$mark, ]) {
            $count[$mark]++;
        }

        return $count;
    }

    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function it_refuses_to_print_a_score_while_anything_is_unmeasured(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وهذا أهمُّ ما في المقياس كلِّه.**
        //
        // أوّلُ تشغيلٍ بعد فصل البيئة أخرج «الجاهزيّة: 10 / 10 (3 من 3)»
        // وسبعةٌ مجهولة — **وذاك أخطرُ من كلّ ما بُني لمنعه**: عينٌ تقرأ
        // العشرةَ ولا تقرأ القوسَ بعدها، فتفتح التسجيلَ لألفي عميلٍ على
        // خادمٍ لم يُسأل.
        //
        // فنسبةُ ثلاثةٍ إلى ثلاثةٍ **عيّنةٌ لا جاهزيّة**، ولا يُختصر
        // المقيسُ والمجهولُ في رقم.
        // ══════════════════════════════════════════════════════════════
        $out = $this->meter();

        $this->assertStringContainsString('غيرُ محسوبة', $out,
            'طُبع رقمٌ وثمّة شروطٌ لم تُقَس — وهو الصمتُ بثوب رقم');

        $this->assertDoesNotMatchRegularExpression('~الجاهزيّة:\s*\d+\s*/\s*10~u', $out,
            'رقمٌ من عشرةٍ على قياسٍ ناقص — يُقرأ حكماً وهو عيّنة');
    }

    /** @test */
    public function the_environment_conditions_are_not_read_from_the_dev_box(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وقِيست الآلةُ الخطأ أوّلَ مرّة.** كان المقياسُ يقرأ `.env`
        // جهازِ التطوير ويحسبه جاهزيّةَ الإنتاج — فقال «التنقيحُ مفتوح»
        // عن حاويةٍ محلّيّةٍ يجب أن يكون فيها مفتوحاً، **ونسب الرقمَ
        // إلى الخادم**.
        //
        // وحاجزُ `docker/entrypoint.sh` يمنع `APP_DEBUG=true` هناك أصلاً
        // فلا تُقلع الحاوية.
        // ══════════════════════════════════════════════════════════════
        $this->assertStringContainsString('لا يُقاس من جهاز التطوير', $this->meter(),
            'شروطُ البيئة تُقرأ من هذا الجهاز وتُنسَب إلى الإنتاج');
    }

    /** @test */
    public function an_unknown_is_never_counted_as_a_pass(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **هذا هو الشرطُ الذي يجعل الرقمَ صادقاً.** ثمانيةٌ لا تُقاس من
        // هنا؛ ومقياسٌ يعدّها نجاحاً يُخرج عشرةً على مشروعٍ لم يُنشَر.
        //
        // ولا يُقاس ذلك بالكلام الذي يقوله المقياسُ عن نفسِه — بل
        // **بمطابقة عدّاده على علاماته**: كم `✓` طُبعت مقابل كم عُدّ
        // ناجحاً، وكم `؟` مقابل كم أُعلن مجهولاً.
        // ══════════════════════════════════════════════════════════════
        $out = $this->meter();

        preg_match('~\((\d+) من (\d+) شرطاً قِيس · (\d+) مجهولاً\)~u', $out, $m);

        $this->assertNotEmpty($m, 'المقياسُ لا يقول كم شرطاً قاس وكم جهِل');

        [, $passed, $total, $unknown] = array_map('intval', $m);

        $marks = $this->marks($out);

        $this->assertGreaterThan(0, $unknown,
            'لا شرطَ «غيرُ معروف» — وثمانيةٌ منها لا تُقاس من هنا قطعاً');

        // **العدّادُ هو العلامات نفسُها.** فلو حُسب المجهولُ نجاحاً
        // لتجاوز البسطُ عددَ `✓` المطبوعة.
        $this->assertSame($marks['✓'], $passed,
            'البسطُ لا يساوي عددَ الناجحات المطبوعة — فشيءٌ غيرُ ناجحٍ عُدّ نجاحاً');

        $this->assertSame($marks['؟'], $unknown,
            'المُعلَنُ مجهولاً لا يساوي عددَ `؟` المطبوعة');

        $this->assertSame($marks['✓'] + $marks['✗'] + $marks['؟'], $total,
            'المقامُ لا يساوي عددَ الشروط المطبوعة');
    }

    /** @test */
    public function it_exits_non_zero_until_everything_is_measured_and_green(): void
    {
        // **ورقمٌ لا يُوقف شيئاً لا يُقرأ.** يخرج بغير صفرٍ ما دام ثمّة
        // شرطٌ ساقطٌ أو مجهول — فيصلح خطوةً في أيّ خطّ نشر.
        $this->assertNotSame(0, Artisan::call('amial:readiness'),
            'يخرج بصفرٍ وثمّة شروطٌ لم تُقَس — فلا يمنع إطلاقاً سابقاً لأوانه');
    }

    /** @test */
    public function every_measured_condition_names_its_source(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **ومقياسٌ يقول «فشل» بلا سببٍ يُرسل صاحبَه يبحث.** فلكلِّ سطرٍ
        // واجبٌ يختلف باختلاف حاله، **ولا يُخلط الواجبان**:
        //
        //   ✓ / ✗  →  يذكر **ما قِيس**: الرقمَ، أو اسمَ المتغيّر،
        //             أو المخزنَ، أو الأمرَ الذي أخرجه.
        //   ؟      →  يذكر **لماذا لم يُقَس، وكيف يُقاس** — فسطرُ
        //             مجهولٍ صامتٌ يُقرأ عطلاً في المقياس لا نقصاً
        //             في القياس.
        //
        // وأسماءُ متغيّراتٍ بعينها لا تُشترَط هنا: `APP_DEBUG` لا يُطبَع
        // من جهاز التطوير أصلاً لأنّ شرطَه مجهول — **وحارسٌ يطلب أثرَ
        // قياسٍ لم يقع يسقط على تصحيحٍ صحيح.**
        // ══════════════════════════════════════════════════════════════
        foreach ($this->rows($this->meter()) as [$mark, $line]) {
            if ($mark === '؟') {
                $this->assertMatchesRegularExpression(
                    '~لا يُقاس|شغّل|تعذّر~u', $line,
                    "سطرٌ مجهولٌ لا يقول لماذا ولا كيف يُقاس: {$line}");

                continue;
            }

            // رقمٌ · اسمُ متغيّرِ بيئةٍ · نصٌّ بعد نقطتين · أمرٌ يُشغَّل
            $this->assertMatchesRegularExpression(
                '~\d|[A-Z][A-Z0-9_]{4,}|:\s*\S|\.(sh|php)~u', $line,
                "سطرٌ مقيسٌ لا يذكر مصدرَه: {$line}");
        }
    }

    /** @test */
    public function the_capacity_ceiling_is_read_from_the_deployed_image(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **والصورةُ المفحوصةُ ليست المشحونة.** Coolify يبني `Dockerfile`
        // لا `Dockerfile.prod` — وهذا مسجَّلٌ في `CLAUDE.md` بعد أن كلّف
        // سقفَ تزامنٍ قدرُه خمسة.
        // ══════════════════════════════════════════════════════════════
        $src = (string) file_get_contents(
            app_path('Console/Commands/ReadinessScoreCommand.php'));

        $this->assertStringContainsString("base_path('Dockerfile')", $src,
            'السقفُ يُقرأ من غير الصورة المنشورة');

        $this->assertStringNotContainsString("base_path('Dockerfile.prod')", $src,
            'يُقرأ من الملفّ الذي لا يُبنى — فيُقاس ما لا يُشحَن');
    }

    /** @test */
    public function the_gate_verdict_is_read_per_tree_not_per_run(): void
    {
        // **وإيصالُ الأمس لا يُقرأ على شيفرة اليوم.** الإيصالُ مفتاحُه
        // شجرةُ المحتوى، فتغيّرُ سطرٍ واحدٍ يُبطله.
        $src = (string) file_get_contents(
            app_path('Console/Commands/ReadinessScoreCommand.php'));

        $this->assertStringContainsString('tree_sha', $src,
            'البوّابةُ تُقرأ بآخر جولةٍ لا بشجرتها — فإيصالُ الأمس يُطمئن اليوم');
    }
}
