<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * AMIAL-LOGIN-GATES-001 — بوّابات الدخول في التطبيق: ثلاثٌ لا خمس.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الثمن الذي دُفع:**
 *
 * كانت قائمةُ نوع الحساب تعرض خمسة أنواع: عميل · تاجر · نقطة بيع ·
 * **وكيل · أدمن**.
 *
 * وقِيس فوجد **صفرُ شاشةٍ للوكيل وصفرُ شاشةٍ للأدمن في التطبيق كلّه**.
 * فمن دخل بأيّهما وصل إلى `WebPortalNoticeScreen` — لافتةٌ تقول «استعمل
 * بوّابة الويب».
 *
 * **بابان يُفتحان على لافتة.** ولا يقف الضررُ عند الحيرة: يُدخل الوكيلُ
 * رقمَه وكلمتَه في شاشةٍ لا تخدمه، ويرى الأدمنُ حقلَ بريدٍ يوحي بأنّ
 * لوحة الإدارة في جيبه.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وإخفاءُ الواجهة ليس حمايةً** (المهارة: `amial-rbac`).
 *
 * فلم يُحذف شيءٌ من الخادم، والحمايةُ حيث كانت: في الوسائط. وهذا الملفُّ
 * يحرس الطرفين — أنّ البوّابتين غابتا عن التطبيق، **وأنّ نقطتيهما ما
 * زالتا تعملان لبوّابتَي الويب**. فحذفٌ يتجاوز الواجهة يُسقط بوّابة
 * الوكيل كلَّها وهي تخدم شركاتِ صرافة.
 */
class AppLoginGatesGuardTest extends TestCase
{
    private const SCREEN = '../02_flutter_app/lib/features/auth/screens/unified_login_screen.dart';

    /**
     * @test
     *
     * **التطبيقُ يعرض ثلاثَ بوّاباتٍ لا أكثر.**
     */
    public function the_app_offers_exactly_three_login_gates(): void
    {
        $src = file_get_contents(base_path(self::SCREEN));

        $this->assertMatchesRegularExpression(
            '/enum AccountKind \{\s*customer,\s*merchant,\s*pos\s*\}/u',
            $src,
            'أنواعُ الدخول في التطبيق ليست ثلاثةً بالضبط — راجع enum AccountKind');

        // **ولا بقيّةَ من البوّابتين في أيّ موضع.**
        // فحقلٌ يبقى أو فرعٌ يُنسى يُظهر «رقم الوكيل» في شاشةٍ بلا وكيل.
        //
        // ولا تُقاس التعليقات: التوثيقُ أعلى الملفّ يذكر ما حُذف وسببَه،
        // فحارسٌ يمسح النصَّ الخام يسقط على شرحِ إصلاحه. **وهذا ثاني
        // موضعٍ يقع فيه هذا في جلسةٍ واحدة** — والقاعدةُ الثانية تذكر
        // عكسَه: حارسٌ مرَّ لأنّ الكلمة وردت في تعليقٍ يصف العطل.
        // **الشيفرةُ تُقاس، لا وصفُها.**
        $code = preg_replace(['#/\*.*?\*/#s', '#^\s*//.*$#m', '#^\s*///.*$#m'], '', $src);

        foreach (['AccountKind.agent', 'AccountKind.admin',
                  '_agentNumCtrl', '_otpStep', 'loginAgentStep1', 'loginAdmin'] as $ghost) {
            $this->assertStringNotContainsString($ghost, (string) $code,
                "بقيّةٌ من بوّابةٍ محذوفة في شاشة الدخول: {$ghost}");
        }
    }

    /**
     * @test
     *
     * **ونقطتا الوكيل والأدمن ما زالتا تعملان — لبوّابتَي الويب.**
     *
     * ══════════════════════════════════════════════════════════════════
     * هذا الشقُّ هو ما يمنع «تنظيفاً» يمتدّ إلى الخادم فيُسقط بوّابةَ
     * الوكيل التي تخدم شركاتِ الصرافة، ولوحةَ الإدارة كلَّها.
     *
     * (وإخفاءُ زرٍّ ليس حمايةً — والعكسُ صحيح: حذفُ زرٍّ ليس سبباً لحذف
     * ما خلفه.)
     */
    public function the_agent_and_admin_endpoints_still_serve_the_web_portals(): void
    {
        $routes = collect(app('router')->getRoutes())->map->uri();

        foreach (['api/v1/agent/auth/login' => 'دخولُ الوكيل',
                  'agent/login' => 'بوّابةُ الوكيل على الويب',
                  'admin/auth/login' => 'دخولُ لوحة الإدارة'] as $uri => $what) {
            $this->assertTrue($routes->contains($uri),
                "{$what} ({$uri}) اختفى — حذفُ بوّابةٍ من التطبيق أسقط خدمةً حقيقيّة");
        }
    }

    /**
     * @test
     *
     * **ومن كانت جلستُه وكيلاً في نسخةٍ أقدم لا يُترك أمام شاشةٍ بيضاء.**
     *
     * ══════════════════════════════════════════════════════════════════
     * فالدورُ محفوظٌ على الجهاز، ومن يُرقّي التطبيق يفتحه بجلسةٍ دورُها
     * `agent`. وبلا وجهةٍ لهذا الدور في `RoleRouter` يقع على `default` —
     * وقد يكون شاشةً بيضاء أو انهياراً.
     *
     * **والترقيةُ الصامتة أخطرُ من التثبيت الجديد**: لا أحد يجرّبها.
     */
    public function an_upgraded_agent_session_still_lands_somewhere_real(): void
    {
        $router = file_get_contents(
            base_path('../02_flutter_app/lib/features/auth/screens/role_router.dart'));

        $this->assertMatchesRegularExpression(
            "/'agent'\s*\|\|\s*'admin'\s*=>\s*WebPortalNoticeScreen/u",
            $router,
            'دورا الوكيل والأدمن بلا وجهة — جلسةٌ محفوظةٌ من نسخةٍ أقدم تقع على شاشةٍ بيضاء');
    }
}
