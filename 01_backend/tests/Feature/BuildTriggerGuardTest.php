<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * AMIAL-CI-COST-001 — **البناءُ يدويٌّ، وهذا الحارسُ يحفظ القرار.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **هذا الملفُّ قُلب رأساً على عقب، والقصّةُ كاملةٌ هنا لئلّا يُقلَب ثالثةً
 * على غير هدى.**
 *
 * **الطورُ الأوّل (AMIAL-CI-TRIGGER-001، ٢٤ أغسطس):** قال صاحبُ المشروع
 * «منذ أيّامٍ وأنا لم أستطع عملَ بناءٍ للتطبيق». وقِيس فكان `codemagic
 * .yaml` **بلا `triggering` إطلاقاً** — لا فرعاً يُراقَب ولا حدثاً
 * يُسمَع. فكلُّ التزامٍ يقف عند الباب حتّى يفتحه إنسان، **ولا سطرَ خطأٍ
 * يقول لماذا**. فأُضيف المُطلِق، وكُتب هذا الحارسُ يشترط وجودَه.
 *
 * **والطورُ الثاني (اليوم): فاتورةُ مئةِ دولار.** أرسل صاحبُ المشروع
 * صورةَ لوحة Codemagic — سبعةُ بناءاتٍ متتاليةٍ × ~٨ دقائقَ على
 * `mac_mini_m2`، **ولا واحدٌ من التزاماتها غيّر ملفَّ فلاتر واحداً**.
 * وقِيس: ١٥٤ التزاماً منذ إضافة المُطلِق، **٩٣ منها بلا أثرٍ في التطبيق**،
 * وكلُّها يُدفَع إلى فرعين فيُبنى مرّتين.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والدرسُ ليس «أخطأتُ في الإعداد» — بل أنّني عالجتُ نصفَ المسألة.**
 *
 * في الملفّ نفسِه كتبتُ: «سقفُ الساعة يعني أنّ بناءً عالقاً يبتلع ساعةً
 * من رصيدٍ محدود» فخفضتُ `max_build_duration`. **أي أنّي كنتُ أعرف أنّ
 * الدقائقَ تُحاسَب، وأوقفتُ الهدرَ في مدّة البناء الواحد ولم أسأل عن
 * عددها.** والعددُ هو الذي أنتج الفاتورة.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وقرارُ صاحب المشروع صريح.** عُرضت عليه أربعُ صيغ — بوّابةُ تغييرٍ على
 * `02_flutter_app` (كانت ستمنع ٩٣ من ١٥٤)، ونزعٌ كامل، وعلامةٌ في رسالة
 * الالتزام، وبوّابةٌ مع فرعٍ واحد — **فاختار النزعَ الكامل**.
 *
 * **وهو يُعيد ما شكا منه في ٢٤ أغسطس، وهو يعلمه ويقبله**: الصمتُ الذي
 * يختاره أرخصُ من فاتورةٍ لا يختارها.
 *
 * **فلا يُعاد المُطلِقُ استنتاجاً من تلك الشكوى القديمة.** ومن قرأ الطورَ
 * الأوّل في سجلّ git أو في `CLAUDE.md` فظنّه مطلباً قائماً، **فليقرأ هذا
 * الحارس: هو ناسخُه.** ولا يُعاد إلّا بطلبٍ جديدٍ صريحٍ من صاحب المشروع.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وما يبقى خارج نظر هذا الحارس، ويُقال ولا يُسكت عنه** (القاعدة
 * السابعة): مُطلِقٌ مضبوطٌ من **واجهة** Codemagic، أو خطّافُ ويبٍ مستقلّ
 * على المستودع. كلاهما خارج الملفّ، فلا يراه أيُّ فحصٍ هنا — ويُطفأ من
 * اللوحة بيد إنسان. **وحارسٌ يُوهم أنّه يغطّي ما لا يغطّيه أسوأ من غيابه.**
 */
class BuildTriggerGuardTest extends TestCase
{
    /**
     * **ويُقرأ بمحلّلٍ حقيقيّ لا بتعبيرٍ نمطيّ.** فمطابقةُ `triggering`
     * نصّاً تمرّ على الكلمة داخل تعليق — **والملفُّ الآن يشرح المُطلِقَ
     * المنزوعَ في ثلاثين سطرَ تعليق**، فحارسٌ نصّيٌّ كان سيقرأ الشرحَ
     * إعداداً ويسقط على لا شيء.
     */
    private function codemagic(): array
    {
        $path = base_path('../codemagic.yaml');

        $this->assertFileExists($path, 'اختفى ملفُّ بناء التطبيق');

        return (array) \Symfony\Component\Yaml\Yaml::parseFile($path);
    }

    /** @return array<string,mixed> */
    private function workflow(): array
    {
        $flows = $this->codemagic()['workflows'] ?? [];

        $this->assertNotEmpty($flows, 'لا مسارَ بناءٍ في الملفّ');

        return (array) reset($flows);
    }

    // ══════════════════════════════════════════════════════════════════

    /**
     * **① لا مُطلِقَ تلقائيّاً — والدفعُ لا يُنفق ريالاً.**
     */
    /** @test */
    public function no_push_silently_starts_a_paid_build(): void
    {
        $trigger = $this->workflow()['triggering'] ?? null;

        $this->assertNull($trigger, sprintf(
            "**عاد المُطلِقُ التلقائيُّ إلى `codemagic.yaml`.**\n\n"
            ."  ما وُجد: %s\n\n"
            ."وقرارُ صاحب المشروع — بعد فاتورةِ مئةِ دولار — أن يكون البناءُ\n"
            ."بضغطةٍ منه في اللوحة وحدَها. وكلُّ دفعةٍ تحت مُطلِقٍ تلقائيٍّ\n"
            ."تشتري ~٨ دقائقَ على آلة Mac، **و٦٠٪ من الالتزامات لا تمسّ\n"
            ."ملفَّ فلاتر واحداً** فتُنتج نسخةً مطابقةً للتي قبلها.\n\n"
            .'ولا يُعاد إلّا بطلبٍ جديدٍ صريحٍ منه — لا استنتاجاً من شكواه '
            .'القديمة «لم أستطع عملَ بناءٍ للتطبيق».',
            json_encode($trigger, JSON_UNESCAPED_UNICODE)));
    }

    /**
     * **② ولا مسارَ ثانٍ يتسلّل بمُطلِقه.**
     *
     * فالفحصُ الأوّلُ يقرأ **أوّلَ** مسارٍ وحدَه، ومسارٌ ثانٍ يُضاف بمُطلِقٍ
     * خاصٍّ به يمرّ من تحته. (وهو صنفُ «حارسٍ ينجح لسببٍ خاطئ».)
     */
    /** @test */
    public function not_one_workflow_in_the_file_carries_a_trigger(): void
    {
        $offenders = [];

        foreach ((array) ($this->codemagic()['workflows'] ?? []) as $name => $flow) {
            if (isset(((array) $flow)['triggering'])) {
                $offenders[] = (string) $name;
            }
        }

        $this->assertSame([], $offenders,
            'مساراتٌ تحمل مُطلِقاً تلقائيّاً: '.implode(' · ', $offenders)
            .' — والبناءُ يدويٌّ بقرارٍ صريح.');
    }

    /**
     * **③ وسقفُ المدّة يبقى منخفضاً — فاليدويُّ يُنفق أيضاً.**
     *
     * ══════════════════════════════════════════════════════════════════
     * فبناءٌ **يُطلقه إنسانٌ** ثمّ يعلق يبتلع سقفَه كاملاً من رصيدٍ
     * محدود. ونزعُ المُطلِق يقلّل **عددَ** البناءات ولا يحدّ **كلفةَ**
     * الواحد منها. والحاجتان مستقلّتان، وقد خلطتُهما من قبل فعالجتُ
     * إحداهما وظننتُ الأخرى معالَجة.
     * ══════════════════════════════════════════════════════════════════
     */
    /** @test */
    public function a_stuck_build_cannot_eat_an_hour_of_credit(): void
    {
        $max = $this->workflow()['max_build_duration'] ?? null;

        $this->assertNotNull($max, 'لا سقفَ لمدّة البناء — فالعالقُ يبتلع الحدَّ الأقصى للخطّة.');

        $this->assertLessThanOrEqual(30, (int) $max, sprintf(
            'سقفُ المدّة %d دقيقة، والبناءُ الناجحُ ~٨. '
            .'فبناءٌ عالقٌ واحدٌ يبتلع ما يكفي لعدّة بناءاتٍ صالحة.',
            (int) $max));
    }

    /** @test */
    public function the_source_fingerprint_step_survives(): void
    {
        // **و«أين تعديلاتي؟» أكثرُ سؤالٍ تكرّر بعد كلّ بناء.** الخطوةُ
        // تطبع الفرعَ والالتزامَ في رأس السجلّ، فيُحسم من السجلّ لا بالظنّ.
        //
        // **وهي أهمُّ الآن لا أقلّ**: البناءُ يدويّ، فقد يُضغط الزرُّ على
        // فرعٍ أو التزامٍ غيرِ الذي يظنّه صاحبُ المشروع.
        $names = array_column((array) ($this->workflow()['scripts'] ?? []), 'name');

        $this->assertNotEmpty(
            array_filter($names, fn ($n) => str_contains((string) $n, 'بصمة المصدر')),
            'سقطت بصمةُ المصدر — فيعود سؤالُ «أين تعديلاتي؟» بلا جواب');
    }

    /** @test */
    public function the_compile_gate_still_runs_before_gradle(): void
    {
        // **وبناءُ Gradle يستغرق ~٤ دقائقَ ثمّ يسقط على خطأ تصريفٍ يُكشَف
        // في عشر ثوانٍ.** وكلُّ بناءٍ صار مقصوداً بضغطةٍ من إنسان — فسقوطُه
        // متأخّراً يُهدر دقائقَ اشتُريت عمداً.
        $names = array_map('strval', array_column((array) ($this->workflow()['scripts'] ?? []), 'name'));

        $gate = null;
        $build = null;

        foreach ($names as $i => $n) {
            if ($gate === null && str_contains($n, 'بوّابة التصريف')) {
                $gate = $i;
            }
            if ($build === null && str_contains($n, 'بناء APK')) {
                $build = $i;
            }
        }

        $this->assertNotNull($gate, 'سقطت بوّابةُ التصريف');
        $this->assertNotNull($build, 'سقطت خطوةُ البناء');

        $this->assertLessThan($build, $gate,
            'بوّابةُ التصريف بعد البناء — فأربعُ دقائقَ تُهدَر على خطأٍ يُكشَف في عشر ثوانٍ');
    }
}
