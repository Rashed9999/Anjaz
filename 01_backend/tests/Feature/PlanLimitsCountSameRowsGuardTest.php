<?php

namespace Tests\Feature;

use App\Support\Access\AccessConstants as A;
use Tests\TestCase;

/**
 * AMIAL-ENTITLEMENTS-005 — **حدّان يُباعان، والصفوفُ المعدودةُ واحدة.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الثمن — قِيس بقراءة الشيفرة، ولا يحتاج تشغيلاً:**
 *
 * `EntitlementService::usageFor` يعدّ الحدّين بالاستعلام **نفسِه حرفاً
 * بحرف**:
 *
 *     'max_employees'   => PosUser::where('merchant_user_id', $id)
 *                              ->where('is_active', true)->count(),
 *     'max_pos_devices' => PosUser::where('merchant_user_id', $id)
 *                              ->where('is_active', true)->count(),
 *
 * وجدولُ الباقات يبيعهما **رقمين مختلفين**:
 *
 * | الباقة | الموظّفون | الأجهزة |
 * |---|---:|---:|
 * | مجّاني | 0 | **1** |
 * | البداية | 0 | **1** |
 * | الأعمال | **5** | 3 |
 * | تاجر محترف | ∞ | ∞ |
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وهذا يُنتج كذبتين متعاكستين في الباقة نفسِها:**
 *
 * ① **باقةُ البداية تَعِد بصفر موظّفين وتُعطي واحداً.** فالصفُّ الذي
 *    يُنشئه «جهازُ بيع» هو صفُّ موظّفٍ عينُه (`PosUser`). فمن اشترى
 *    البدايةَ يُنشئ «جهازاً» فيحصل على موظّفٍ كامل — **والباقةُ تقول
 *    `employees = 0`**.
 *
 * ② **وباقةُ الأعمال تبيع خمسةَ موظّفين وتُسلّم ثلاثة.** فعند الصفّ
 *    الثالث يبلغ حدُّ الأجهزة (3) فيُقفَل الباب — **قبل أن يبلغ حدُّ
 *    الموظّفين (5) الذي دفع ثمنَه**.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وليس عطلَ حراسة**: الحارسُ يعمل، والعدّادُ يعمل، والاختباراتُ تمرّ.
 * العطلُ **في أنّ الباقةَ تبيع كمّيّتين لشيءٍ واحد** — ولا يظهر إلّا حين
 * يُسأل: أيَّ صفوفٍ يعدّ كلٌّ منهما؟
 *
 * **والحسمُ قرارُ تسعيرٍ لا قرارُ شيفرة**، ولذلك يُثبّت هنا ولا يُغلَق:
 *
 *   (أ) الجهازُ والموظّفُ شيءٌ واحد ⇒ يُحذف أحدُ الحدّين من جدول الباقات
 *   (ب) أو هما شيئان ⇒ يُفصَل الجدولُ، ولا يُعدّ الجهازُ موظّفاً
 *
 * وحتّى يُحسَم، **يُمنَع أن يزيد التعارضُ صامتاً**.
 */
class PlanLimitsCountSameRowsGuardTest extends TestCase
{
    /**
     * الحدودُ التي يُعرف يقيناً أنّها تُقرأ من الجدول نفسِه.
     *
     * تُقرأ من `EntitlementService::usageFor` — وهي `PosUser` لكليهما.
     *
     * @var array<int,array{0:string,1:string}>
     */
    private const SHARED_ROWS = [
        ['employees', 'pos_devices'],
    ];

    /**
     * @test
     *
     * **حدّان على صفوفٍ واحدة يجب أن يحملا الرقمَ نفسَه في كلّ باقة.**
     *
     * وإلّا فالأصغرُ يحكم والأكبرُ وعدٌ لا يُنفَّذ — أو العكس: الأكبرُ
     * يُعطي ما لم تبعه الباقة.
     *
     * **ورسالةُ السقوط تحمل الجدولَ كاملاً** — فيُقرأ القرارُ التجاريُّ
     * من الأرقام لا من الوصف.
     */
    public function two_limits_that_count_the_same_rows_must_sell_the_same_number(): void
    {
        $conflicts = [];

        foreach (self::SHARED_ROWS as [$a, $b]) {
            foreach (A::ALL_PLANS as $plan) {
                $limits = A::PLAN_LIMITS[$plan] ?? [];

                $x = $limits[$a] ?? null;
                $y = $limits[$b] ?? null;

                if ($x === null || $y === null || $x === $y) {
                    continue;
                }

                $conflicts[] = sprintf(
                    '%-14s %s = %-4s · %s = %-4s   ⇒ %s',
                    A::PLAN_LABELS[$plan] ?? $plan,
                    $a, $this->show($x), $b, $this->show($y),
                    $this->consequence($x, $y, $a, $b),
                );
            }
        }

        // ══════════════════════════════════════════════════════════════
        // **التعارضُ يُثبَّت بعدده لا يُصفَّر — لأنّه دَينٌ تجاريٌّ لا عطلُ
        // شيفرة.**
        //
        // ثلاثةٌ اليوم، وكلُّها مقيسة:
        //
        //   مجّاني   : موظّفون 0 · أجهزة 1  ⇒ يُعطي موظّفاً لم يُبَع
        //   البداية  : موظّفون 0 · أجهزة 1  ⇒ كذلك
        //   الأعمال  : موظّفون 5 · أجهزة 3  ⇒ يبيع خمسةً ويُسلّم ثلاثة
        //
        // **والقرارُ صدر: هما حدّان مستقلّان** (صاحبُ المشروع، ٢٠٢٦-٠٨-١٦):
        // «الموظّف ≠ الجهاز. لا تدمجهما ولا تحذف أحدهما.»
        //
        // **ولا يُنفَّذ على المخطّط الحاليّ** — وهذا عائقٌ تقنيٌّ مقيس:
        //
        //   `pos_users` : user_id · merchant_user_id · pos_number ·
        //                 display_name · is_active · permissions
        //
        // **لا عمودَ يميّز جهازاً من موظّف**، ولا مسارَ يُنشئ جهازاً:
        // المنشئُ الوحيدُ `MerchantStaffController` وهو يُنشئ **موظّفاً**.
        // فكلُّ صفٍّ اليوم موظّف، و`max_pos_devices` حدٌّ يُباع بلا موردٍ
        // مستقلٍّ خلفه.
        //
        // فالتنفيذُ يحتاج مخطّطاً أوّلاً: عمودَ `kind` (‏موظّف/جهاز) أو
        // جدولَ أجهزةٍ مستقلّاً، **ثمّ** عدّادين منفصلين ومسارَ إنشاءٍ
        // للجهاز. واختراعُ تمييزٍ الآن يُنتج رقمين كاذبين مكان رقمٍ واحد.
        //
        // فيُمنَع **أن يزيد صامتاً**، ويُوقَظ الحارسُ عند أيّ تغيّرٍ في
        // الاتّجاهين — فالإصلاحُ يجب أن يُنزِل الرقمَ هنا معه، وإلّا مرّ
        // الإصلاحُ بلا أن يُلاحظه أحد.
        // ══════════════════════════════════════════════════════════════
        // **ونزل من ثلاثةٍ إلى اثنين — ولا إصلاحَ وقع.**
        //
        // توحيدُ الكتالوج إلى ثلاث باقات حذف باقةً، فذهب تعارضُها معها.
        // **والتعارضُ نفسُه قائمٌ في الباقيتين**: «موظّفون» و«أجهزة نقاط
        // بيع» ما زالا يُباعان برقمين ويعدّان `PosUser` النشِطةَ نفسَها.
        //
        // فالرقمُ يُنزَل كما يطلب الحارسُ، **ويُقال سببُه**: حذفُ باقةٍ
        // لا حسمُ التسعير. والحسمُ ما زال قرارَك: يُحذف أحدُ الحدّين، أو
        // يُفصَل العدّاد فلا يُعدّ الجهازُ موظّفاً.
        // ══════════════════════════════════════════════════════════════
        $this->assertCount(2, $conflicts, sprintf(
            "عددُ التعارضات صار %d وكان 2 — وهي حدودٌ تُباع بأرقامٍ مختلفة "
            . "**وتعدّ الصفوفَ نفسَها** (‏`PosUser` النشِطة):\n\n  %s\n\n"
            . "إن كان النقصُ إصلاحاً فأنزِل الرقمَ هنا معه.\n"
            . "والحسمُ قرارُ تسعيرٍ لا قرارُ شيفرة:\n"
            . "  (أ) الجهازُ والموظّفُ شيءٌ واحد ⇒ يُحذف أحدُ الحدّين\n"
            . "  (ب) أو هما شيئان ⇒ يُفصَل العدّاد، ولا يُعدّ الجهازُ موظّفاً",
            count($conflicts), implode("\n  ", $conflicts)));
    }

    /**
     * @test
     *
     * **وكلُّ حدٍّ في السجلّ له عمودٌ في جدول الباقات.**
     *
     * قدرةٌ تُعلن `limit('max_widgets')` ولا عمودَ له في `PLAN_LIMITS`
     * تقرأ `-1` (بلا حدّ) **فتمرّ أبداً** — حدٌّ مُعلَنٌ لا يحدّ شيئاً،
     * وهو حارسٌ يُطمئن ولا يحرس.
     */
    public function every_declared_limit_key_has_a_column_in_the_plan_table(): void
    {
        $columns = array_keys(A::PLAN_LIMITS[A::PLAN_FREE] ?? []);

        $orphans = [];

        foreach (\App\Support\Access\CapabilityRegistry::all() as $cap) {
            $key = $cap->toArray()['limit'];

            if ($key === null) {
                continue;
            }

            // **التخطيطُ يُنسَخ من `EntitlementService::limitColumn`** —
            // ولا يُشتقّ بحذف البادئة. فـ`max_locations` تتبع عمودَ
            // **الفروع** لا عموداً باسمها، ولو اشتُقَّ الاسمُ آليّاً لأبلغ
            // هذا الحارسُ عن يتيمٍ كاذب.
            //
            // (والنسخُ هنا دَينٌ معلوم: التخطيطُ `private`. ويُمسك انحرافُه
            // بالاختبار أدناه — إن أُضيف مفتاحٌ هناك ولم يُضَف هنا سقط.)
            $column = match ($key) {
                'max_products' => 'products',
                'max_employees' => 'employees',
                'max_branches' => 'branches',
                'max_pos_devices' => 'pos_devices',
                'max_locations' => 'branches',
                default => null,
            };

            if ($column === null) {
                $orphans[] = "{$cap->code} → {$key} (لا تخطيطَ له في limitColumn)";

                continue;
            }

            if (! in_array($column, $columns, true)) {
                $orphans[] = "{$cap->code} → {$key} (لا عمودَ «{$column}»)";
            }
        }

        $this->assertSame([], $orphans, sprintf(
            "قدرةٌ تُعلن حدّاً لا عمودَ له في جدول الباقات — فتقرأ «بلا حدّ» "
            . "وتمرّ أبداً:\n  %s",
            implode("\n  ", $orphans)));
    }

    private function show(int $v): string
    {
        return $v < 0 ? '∞' : (string) $v;
    }

    private function consequence(int $x, int $y, string $a, string $b): string
    {
        if ($x < 0 || $y < 0) {
            return 'أحدُهما بلا حدٍّ فيُلغي الآخر';
        }

        return $x < $y
            ? "«{$b}» وعدٌ لا يُنفَّذ — «{$a}» يُقفل أوّلاً"
            : "«{$a}» وعدٌ لا يُنفَّذ — «{$b}» يُقفل أوّلاً";
    }
}
