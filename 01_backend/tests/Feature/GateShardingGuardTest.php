<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * AMIAL-GATE-SHARD-001 — **تقسيمٌ يبتلع ملفّاً يُخرج «نجح» على ما لم يُشغَّل.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ما قِيس، بعد أن صارت البوّابةُ تقيس نفسَها:**
 *
 *     466 ث  ٩) مجموعة الاختبارات   ← ٧٤٪ من ٦٢٨
 *      42 ث  ١) تركيب PHP
 *
 * والآلةُ أربعةُ أنوية. فثلاثةُ أرباع الوقت كانت تمضي على ربعها.
 *
 * **وأُثبت قبل الاعتماد، والعددُ هو الحَكَم:**
 *
 *     متتابعاً : 466 ث · 3118 ناجحاً · 17 مُقلِقاً · 2 مُخطّىً
 *     بأربعٍ   : 155 ث · 3118 ناجحاً · 17 مُقلِقاً · 2 مُخطّىً
 *      php -l  :  43 ث  →  11 ث
 *
 * **ونقصٌ في العدد كان سيعني تقسيماً يبتلع لا تسريعاً.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والخطرُ الذي يحرسه هذا الملفّ ليس البطء بل الصمت.** مقسِّمٌ يُسقط
 * ملفّاً لا يُخرج خطأً: يُخرج **رقماً أصغرَ بقليل** ويمضي أخضرَ. ومن
 * يقرأ «نجح ٣٣ فحصاً» لا يعدّ الاختبارات.
 *
 * وهو نمطٌ وقع في هذه البوّابة بعينها: سقطت الطبقةُ التاسعة مرّةً بـ`✓`
 * **فارغ** لأنّ الذاكرةَ نفدت فلم يُطبع `Tests:` إطلاقاً، فلم يجد الشرطُ
 * شيئاً ومضى إلى `else`. فيُطلَب **إثباتٌ موجب** لا غيابُ خطأ.
 */
class GateShardingGuardTest extends TestCase
{
    private function shardScript(): string
    {
        $p = base_path('scripts/test-shards.sh');

        $this->assertFileExists($p, 'اختفى المقسِّم — والبوّابةُ تناديه');

        return (string) file_get_contents($p);
    }

    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function the_splitter_refuses_to_run_if_a_file_would_be_dropped(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **الشرطُ الأوّل، ويقع قبل التشغيل لا بعده.** بعدَه لا سبيلَ
        // إلى معرفة أنّ ملفّاً غاب: الناتجُ رقمٌ أصغرُ بلا أثر.
        // ══════════════════════════════════════════════════════════════
        $src = $this->shardScript();

        $this->assertStringContainsString('ASSIGNED', $src,
            'المقسِّمُ لا يعدّ ما وزّعه — فإسقاطُ ملفٍّ يمرّ صامتاً');

        $this->assertMatchesRegularExpression(
            '~ASSIGNED.{0,60}TOTAL_FILES~s', $src,
            'لا مقارنةَ بين الموزَّع والموجود');

        $this->assertMatchesRegularExpression('~DUPES~', $src,
            'لا فحصَ للتكرار — وملفٌّ في شريحتين يُضخّم العدَّ فيُخفي نقصاً');
    }

    /** @test */
    public function a_crashed_shard_is_never_read_as_success(): void
    {
        // **وشريحةٌ نفدت ذاكرتُها لا تطبع `Tests:` إطلاقاً.** فغيابُ
        // السطر يجب أن يكون فشلاً، لا «لم أجد فشلاً».
        $src = $this->shardScript();

        $this->assertStringContainsString('BROKEN', $src,
            'انهيارُ شريحةٍ لا يُحصى — فثلاثةُ أرباع المجموعة تمرّ خضراء');

        $this->assertMatchesRegularExpression(
            "~! echo \"\\\$LINE\" \\| grep -q 'passed'~", $src,
            'لا إثباتَ موجب: الشريحةُ تُقرأ ناجحةً بغياب سطر النتيجة');
    }

    /** @test */
    public function each_shard_gets_its_own_database(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وقاعدةٌ مشتركةٌ تُنتج إخفاقاً لا علاقةَ له بالشيفرة.**
        // `RefreshDatabase` يُهاجر ويُفرغ، فعمليّتان على قاعدةٍ واحدة
        // تمحوان بيانات بعضهما في منتصف اختبار.
        //
        // وذاك أسوأُ من البطء: يُرسل من يقرؤه خلف عطلٍ لا وجودَ له —
        // وقد وقع في هذا المشروع ثلاثَ مرّاتٍ بصورةٍ أخرى.
        // ══════════════════════════════════════════════════════════════
        $src = $this->shardScript();

        $this->assertMatchesRegularExpression('~DB_DATABASE="\$\{BASE_DB\}_s\$\{i\}"~', $src,
            'الشرائحُ تتقاسم قاعدةً — فتمحو بيانات بعضها');

        // ══════════════════════════════════════════════════════════════
        // **وتُبنى من الصفر لا `IF NOT EXISTS` وحدَها.** قاعدةُ شريحةٍ
        // تركتها جولةٌ منقطعةٌ في منتصف هجرةٍ تبقى منجرفةً إلى الأبد،
        // فتُخرج إخفاقاً لا علاقةَ له بالشيفرة — وقد وقع: `forge_s1`
        // حملت ٢٣٦ هجرةً «تمّت» وينقصها جدول.
        // ══════════════════════════════════════════════════════════════
        $this->assertStringContainsString('DROP DATABASE IF EXISTS', $src,
            'قاعدةُ الشريحة لا تُبنى من الصفر — فحالةٌ منجرفةٌ تبقى بين الجولات');

        $this->assertStringContainsString('CREATE DATABASE', $src,
            'لا تُنشأ قاعدةُ الشريحة — فأوّلُ تشغيلٍ يسقط');
    }

    /** @test */
    public function the_gate_falls_back_to_serial_rather_than_skipping(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وسرعةٌ تتحوّل إلى تخطٍّ عند أوّل عائقٍ أسوأ من البطء.**
        //
        // إن تعذّر التقسيم — لا صلاحيّةَ إنشاءِ قواعد على خادمٍ آخر،
        // أو تقسيمٌ رفض نفسَه — **تجري المجموعةُ متتابعةً**. ولا تُقال
        // «مُخطّاة»، فالطبقةُ المُخطّاةُ لا تُعدّ نجاحاً وهذه يجب أن تُعدّ.
        // ══════════════════════════════════════════════════════════════
        $gate = (string) file_get_contents(base_path('scripts/verify.sh'));
        $gate = preg_replace('~^\s*#[^\n]*$~m', '', $gate) ?? '';

        $this->assertStringContainsString('test-shards.sh', $gate,
            'البوّابةُ لا تستعمل المقسِّم — فالطبقةُ ما زالت ٤٦٦ ث');

        $this->assertMatchesRegularExpression(
            '~SHARD_RC -eq 3.{0,400}artisan test~s', $gate,
            'لا ارتدادَ متتابع: تعذُّرُ التقسيم يُسقط الطبقةَ بدل أن يُبطئها');
    }

    /** @test */
    public function the_syntax_layer_uses_every_core(): void
    {
        // **و`php -l` عمليّةٌ لكلّ ملفّ** — فالتوازي ربحٌ خالصٌ لا يغيّر
        // ما يُفحَص. قِيس: ٤٣ ث → ١١ ث.
        $gate = (string) file_get_contents(base_path('scripts/verify.sh'));

        $this->assertMatchesRegularExpression('~xargs -0 -r -n1 -P ~', $gate,
            'فحصُ التركيب ما زال على نواةٍ واحدة');
    }

    /** @test */
    public function the_gate_reports_where_its_time_went(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وبوّابةٌ لا تقول أين ذهب وقتُها لا تُسرَّع.**
        //
        // قيل «الاختباراتُ بطيئة» — وكان تخميناً؛ ولا شيءَ في المخرَج
        // يقيس طبقةً واحدة. وأوّلُ قياسٍ صحّح تقديرين معاً: العنقُ
        // ٧٤٪ في طبقةٍ واحدة، **والإجماليُّ عشرُ دقائقَ لا نصفُ ساعة**.
        // ══════════════════════════════════════════════════════════════
        $gate = (string) file_get_contents(base_path('scripts/verify.sh'));

        $this->assertStringContainsString('gate_timing_report', $gate,
            'البوّابةُ لا تطبع زمنَ طبقاتها — فالعنقُ يُخمَّن');

        $this->assertMatchesRegularExpression('~gate_timing_report\s*$~m', $gate,
            'الدالّةُ معرَّفةٌ ولا تُنادى — مبنيٌّ ولا يُوصَل إليه');
    }
}
