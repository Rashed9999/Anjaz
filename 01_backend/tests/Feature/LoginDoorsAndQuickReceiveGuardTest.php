<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * AMIAL-LOGIN-DOORS-002 · AMIAL-QUICK-RECEIVE-002
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الثمنُ الذي وُلد منه هذا الحارس:** أُعيد بناءُ شاشة الدخول (١٣٥١ سطراً
 * تغيّرت)، **فضاع في إعادة الكتابة شرحُ لماذا صارت الأبوابُ ثلاثةً بعد أن
 * كانت خمسة**.
 *
 * والشيفرةُ نجت — التصميمُ ثلاثيٌّ كما كان. **والضائعُ هو العلّة.** وبلا
 * العلّة يُعاد البابان بعد شهرٍ بحسن نيّة: «لماذا لا يدخل الوكيلُ من
 * التطبيق؟». فيُدخل الوكيلُ رقمَه في شاشةٍ لا تخدمه، ويرى الأدمنُ حقلَ
 * بريدٍ يوحي بأنّ لوحة الإدارة في جيبه.
 *
 * **وقرارٌ بلا سببٍ مكتوبٍ يُنقض عند أوّل سؤال.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وقياسٌ وقع في فخٍّ يستحقّ التسجيل:** قِيست الشاشةُ قبل الدمج بـ`grep`
 * عن `loginAgent`، فظهرت في القديم وغابت في الجديد — **وبدا أنّ نداءً
 * حُذف**. والحقيقةُ أنّها كانت في **تعليقٍ عربيٍّ يشرح أنّها لا تُنادى**.
 *
 * وهو نفسُ العطل المسجَّل في `CLAUDE.md`: «التعليقُ الذي يصف العطلَ كان
 * يُخفيه» — واقعاً هذه المرّةَ بالمقلوب: **التعليقُ الذي يصف الغيابَ أوهم
 * بالحضور.**
 */
class LoginDoorsAndQuickReceiveGuardTest extends TestCase
{
    private function login(): string
    {
        $p = base_path('../02_flutter_app/lib/features/auth/screens/unified_login_screen.dart');

        if (! is_file($p)) {
            $this->markTestSkipped('التطبيقُ غيرُ موجودٍ في هذه البيئة');
        }

        return (string) file_get_contents($p);
    }

    // ══════════════════════════════════════════════════════════════════
    //  ① ثلاثةُ أبوابٍ لا خمسة — والعلّةُ مكتوبة
    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function the_app_offers_three_doors_only(): void
    {
        $this->assertStringContainsString(
            'enum AccountKind { customer, merchant, pos }', $this->login(),
            'عاد بابٌ رابعٌ إلى شاشة الدخول — والوكيلُ والأدمنُ لا شاشةَ '
            . 'لهما في التطبيق، فبابُهما يُفتح على لافتة');
    }

    /** @test */
    public function the_reason_the_two_doors_were_removed_survives_a_rewrite(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وعلّةٌ لا تُقال تُنسى.** ضاع هذا الشرحُ مرّةً في إعادة بناءٍ
        // للشاشة، واستُعيد. وهذا الحارسُ يمنع ضياعَه ثانية — فالشيفرةُ
        // تُراجَع، والقرارُ الذي بلا سببٍ يُنقض.
        // ══════════════════════════════════════════════════════════════
        $src = $this->login();

        foreach ([
            'WebPortalNoticeScreen',   // إلى أين كان يصل الوكيلُ والأدمن
            'loginAgentStep1',         // ولم يُحذف شيءٌ من الخادم
            'RoleRouter',              // وجلسةٌ قديمةٌ لا تُترك أمام بياض
        ] as $anchor) {
            $this->assertStringContainsString($anchor, $src,
                "ضاع من الشرح ذكرُ «{$anchor}» — وقرارٌ بلا سببٍ مكتوبٍ "
                . 'يُنقض عند أوّل سؤال');
        }

        $this->assertStringContainsString('وإخفاءُ الواجهة ليس حمايةً', $src,
            'ضاع التنبيهُ إلى أنّ الحمايةَ في الوسائط لا في إخفاء الشاشة — '
            . 'وهو ما يمنع من يقرأ هذا أن يظنّ البابَ مُقفلاً بحذف زرّه');
    }

    // ══════════════════════════════════════════════════════════════════
    //  ② والاستلامُ قبل الدخول يستقبل ولا يكشف
    // ══════════════════════════════════════════════════════════════════

    private function quickReceive(): string
    {
        $p = base_path('../02_flutter_app/lib/features/auth/screens/quick_receive_screen.dart');

        if (! is_file($p)) {
            $this->markTestSkipped('التطبيقُ غيرُ موجودٍ في هذه البيئة');
        }

        return (string) file_get_contents($p);
    }

    /** @test */
    public function the_pre_auth_screen_is_a_plain_widget_with_no_api_of_its_own(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **شاشةٌ تعمل قبل المصادقة يجب ألّا تسأل الخادمَ شيئاً.**
        //
        // فنداءٌ واحدٌ منها بلا رمزٍ إمّا يُرفض (فالشاشةُ زينة) وإمّا
        // يُقبل — **وذاك بابٌ يقرأ بياناتِ حسابٍ بلا دخول**.
        //
        // فتُبنى من حالةٍ محفوظةٍ محلّيّاً تُمرَّر إليها، ولا `ApiClient`
        // فيها إطلاقاً.
        // ══════════════════════════════════════════════════════════════
        $src = $this->quickReceive();

        $this->assertStringNotContainsString('ApiClient', $src,
            'شاشةُ ما قبل الدخول تسأل الخادم — إمّا تُرفض فتكون زينةً، '
            . 'وإمّا تُقبل فتكون باباً يقرأ بلا مصادقة');

        $this->assertStringNotContainsString('getData', $src);
        $this->assertStringNotContainsString('postData', $src);
    }

    /** @test */
    public function it_can_only_ever_show_the_two_values_it_is_given(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **ولا يُقاس هذا بالبحث عن كلمة «رصيد».**
        //
        // كُتب هذا الحارسُ أوّلَ مرّةٍ يبحث عن `balance` و«سحب» و«تحويل»
        // فسقط — **لأنّ الشاشةَ تحوي نصّاً يطمئن المستعمل بأنّها لا تسمح
        // بالسحب ولا التحويل**، وتعليقاً يقول إنّها لا تعرض الرصيد.
        //
        // فالنصُّ الذي ينفي الشيءَ طابقه المقياسُ إثباتاً له. وهو العطلُ
        // المسجَّل في `CLAUDE.md` بعينه، واقعاً على حارسٍ كتبتُه توّاً.
        //
        // **فالقياسُ على ما تستطيع الشاشةُ عرضَه لا على ما تكتبه**:
        // صنفٌ عديمُ الحالة، مُعامِلاه نصّان يُمرَّران إليه — فلا رصيدَ
        // يبلغها ولا حركةٌ، مهما كُتب فيها.
        // ══════════════════════════════════════════════════════════════
        $src = $this->quickReceive();

        $this->assertStringContainsString('extends StatelessWidget', $src,
            'صارت الشاشةُ ذاتَ حالة — فقد تجلب ما لم تُعطَه');

        // الحقولُ التي تحملها — ولا ثالثَ لهما.
        if (! preg_match_all('/^\s*final\s+(\w+)\s+(\w+);/m', $src, $m)) {
            $this->fail('لم تُقرأ حقولُ الصنف');
        }

        $this->assertSame(['displayName', 'paymentAddress'], $m[2],
            'حقلٌ ثالثٌ دخل شاشةَ ما قبل المصادقة — والسطحُ للاستقبال وحدَه');

        // **ولا تنقل إلى شاشةٍ أخرى** — فمخرجٌ منها إلى سطحٍ ماليٍّ
        // يُبطل كلَّ ما سبق.
        $this->assertStringNotContainsString('Get.to(', $src,
            'الشاشةُ تنقل إلى سطحٍ آخرَ قبل المصادقة');
        $this->assertStringNotContainsString('Navigator.push', $src);
    }

    /** @test */
    public function the_address_is_masked_on_screen(): void
    {
        // **ويُقنَّع العنوانُ في النصّ وإن كان في الرمز كاملاً.** الرمزُ
        // يُمسَح بقصدٍ من المرسِل، والنصُّ يُقرأ بنظرةٍ من فوق الكتف.
        $this->assertStringContainsString('••••', $this->quickReceive(),
            'عنوانُ الاستلام يُعرَض كاملاً نصّاً في شاشةٍ قبل المصادقة');
    }

    /** @test */
    public function it_is_only_reachable_after_a_previous_customer_login(): void
    {
        // **ولا يُفتح السطحُ على جهازٍ لم يدخل منه أحد** — وإلّا صار
        // الرمزُ يُعرض بلا صاحب.
        $src = $this->login();

        $this->assertMatchesRegularExpression(
            "~_openQuickReceive.{0,400}last == null~s", $src,
            'يُفتح الاستلامُ السريع بلا مستخدمٍ محفوظ');

        $this->assertStringContainsString("last.kind != 'customer'", $src,
            'يُفتح الاستلامُ السريع لغير العميل — ولحسابات التاجر ونقطة '
            . 'البيع أسطحُ قبضٍ أخرى بقيودٍ أخرى');
    }

    /** @test */
    public function the_qr_payload_matches_what_the_product_already_scans(): void
    {
        // ══════════════════════════════════════════════════════════════
        // **ورمزٌ لا يقرؤه ماسحُ المنتج ليس ميزةً بل صورة.**
        //
        // وقِيس: `qr_code_download_or_share_screen` يشفّر رقمَ الحساب أو
        // الهاتفَ **خاماً**، و`verifyRecipient` في الخادم يقبل الاثنين.
        // فالحمولةُ متوافقةٌ — والادّعاءُ قِيس ولم يُصدَّق.
        // ══════════════════════════════════════════════════════════════
        // ══════════════════════════════════════════════════════════════
        // **ولا يُطابَق اسمُ المتغيّر.**
        //
        // كُتب أوّلَ مرّةٍ `'data: paymentAddress'` حرفاً — **فسقط على
        // تحسينٍ صحيح**: أعاد كودكس تسميتَه `receiveAddress` والحمولةُ
        // هي هي. وحارسٌ يمنع إعادةَ تسميةٍ سليمةٍ يُطفَأ عند أوّل مرّة،
        // وهو الصنفُ المسجَّل في `CLAUDE.md`.
        //
        // فالعقدُ الذي يهمّ اثنان، ويُقاسان لا يُفترضان:
        //
        //   ١) الحمولةُ **قيمةٌ خام**، لا غلافُ JSON ولا رابط — فماسحُ
        //      المنتج يقرأ النصَّ كما هو ويرسله إلى `verifyRecipient`.
        //   ٢) وهي **ليست الهاتف** — والشاشةُ تُفتح قبل الدخول، فرمزٌ
        //      يحمل الرقمَ يُفشيه لكلّ من يمسحه.
        // ══════════════════════════════════════════════════════════════
        $qr = $this->quickReceive();

        $this->assertMatchesRegularExpression(
            '~Qr(?:ImageView|DisplayWidget)\(.{0,400}?\bdata:\s*([A-Za-z_][A-Za-z0-9_.]*)\s*,~s', $qr,
            'حمولةُ الرمز ليست متغيّراً مفرداً — فإمّا غلافٌ أو نصٌّ مركَّب، '
            . 'وماسحُ المنتج يقرأ القيمةَ الخام');

        preg_match('~Qr(?:ImageView|DisplayWidget)\(.{0,400}?\bdata:\s*([A-Za-z_][A-Za-z0-9_.]*)\s*,~s', $qr, $m);
        $payloadVar = $m[1] ?? '';

        $this->assertMatchesRegularExpression('~(?i)address~', $payloadVar,
            "حمولةُ الرمز «{$payloadVar}» ليست عنوانَ استلام — "
            . 'والماسحُ يتوقّع معرّفَ الحساب');

        $this->assertDoesNotMatchRegularExpression('~(?i)phone~', $payloadVar,
            "حمولةُ الرمز «{$payloadVar}» تحمل الهاتفَ — والشاشةُ تُفتح "
            . 'قبل الدخول، فيُفشى الرقمُ لكلّ من يمسح');

        $profileQr = base_path(
            '../02_flutter_app/lib/features/setting/screens/qr_code_download_or_share_screen.dart');

        if (is_file($profileQr)) {
            $this->assertStringContainsString('widget.phoneNumber',
                (string) file_get_contents($profileQr),
                'شاشةُ QR الملفّ لم تعد تقبل الهاتفَ بديلاً — '
                . 'فحمولةُ الاستلام السريع صارت يتيمة');
        }
    }
}
