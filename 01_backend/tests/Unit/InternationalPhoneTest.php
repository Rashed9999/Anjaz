<?php

namespace Tests\Unit;

use App\Support\Phone;
use PHPUnit\Framework\TestCase;

/**
 * AMIAL-PHONE-002 — **رقمٌ أجنبيٌّ كان يُصنَع يمنيّاً بالقوّة.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الطلب:** «المفترض أن طريقة التسجيل عبر الهاتف تكون عالميّة».
 *
 * وقِيس قبل كتابة سطرٍ من العلاج، فلم تكن الميزةُ ناقصةً — **كان البابُ
 * مكسوراً**:
 *
 *     +966501234567  →  967966501234567
 *     +201001234567  →  967201001234567
 *     +15551234567   →  96715551234567
 *
 * السطرُ الأخير في `canonical()` كان `return '967' . $p;` بلا شرط. وحقلُ
 * `dial_country_code` في نموذج التسجيل يُملأ ثمّ **يُرمى**.
 *
 * **والعطلُ صامت:** الرقمُ الناتجُ صالحُ الشكل وكاذبُ المعنى. فلا OTP
 * يصل، ولا خطأَ في أيّ سجلّ، والمستعملُ يرى «أُرسل الرمز» ثمّ لا يأتي شيء.
 */
class InternationalPhoneTest extends TestCase
{
    // ══════════════════════════════════════════════════════════════════
    //  ① الرقمُ الأجنبيُّ يبقى أجنبيّاً
    // ══════════════════════════════════════════════════════════════════

    /**
     * @test
     *
     * @dataProvider foreignNumbers
     */
    public function a_foreign_number_keeps_its_own_country_code(string $input, string $expected): void
    {
        $this->assertSame($expected, Phone::canonical($input),
            "أُلصقت 967 برقمٍ أجنبيّ — فلا OTP يصل ولا خطأَ في أيّ سجلّ");
    }

    public static function foreignNumbers(): array
    {
        return [
            'السعوديّة' => ['+966501234567', '966501234567'],
            'مصر' => ['+201001234567', '201001234567'],
            'الإمارات' => ['+971501234567', '971501234567'],
            'أمريكا' => ['+15551234567', '15551234567'],
            'بريطانيا' => ['+447700900123', '447700900123'],
            'بصيغة 00' => ['00966501234567', '966501234567'],
            'بفراغاتٍ ورموز' => ['+966 50-123 4567', '966501234567'],
            'وصفرٌ وطنيٌّ بعد المفتاح' => ['+9660501234567', '966501234567'],
        ];
    }

    // ══════════════════════════════════════════════════════════════════
    //  ② واليمنيُّ لا يتغيّر بحرف — شرطُ صحّة هذا كلِّه
    // ══════════════════════════════════════════════════════════════════

    /**
     * @test
     *
     * @dataProvider yemeniForms
     */
    public function every_stored_yemeni_form_normalises_exactly_as_before(string $input): void
    {
        // **والتوافقُ الخلفيُّ ليس تحسيناً — هو شرطُ ألّا يُقفَل المنتجُ
        // على مستعمليه.** كلُّ رقمٍ في القاعدة اليوم يمنيّ، وأيُّ تغييرٍ
        // في ناتجه يمنع الدخولَ والتحويلَ معاً.
        $this->assertSame('967771000001', Phone::canonical($input));
    }

    public static function yemeniForms(): array
    {
        return [
            ['+967771000001'], ['00967771000001'], ['967771000001'],
            ['771000001'], ['0771000001'], ['+967 77-100 0001'],
            ['+9670771000001'], ['nulL771000001'],
        ];
    }

    /** @test */
    public function a_yemeni_landline_is_still_yemeni(): void
    {
        // **ولمَ لا يُخمَّن من الأرقام:** رقمُ عدن الأرضيُّ يبدأ بـ`2`،
        // ومفتاحُ مصرَ `20`. فمن خمّن قلبَ رقماً محلّيّاً إلى مصريّ.
        // والفاصلُ هو `+`/`00` — علامةُ «هذا دوليّ» في كلّ الأنظمة.
        $this->assertSame('9672234567', Phone::canonical('2234567'));
        $this->assertSame('9672234567', Phone::canonical('02234567'));
    }

    // ══════════════════════════════════════════════════════════════════
    //  ③ والتطبيعُ متعادٍ — وإلّا فكلُّ قراءةٍ تُنتج رقماً ثالثاً
    // ══════════════════════════════════════════════════════════════════

    /**
     * @test
     *
     * @dataProvider everyShape
     */
    public function normalising_twice_gives_the_same_answer(string $input): void
    {
        // ══════════════════════════════════════════════════════════════
        // **وهذا أخطرُ ما في الإصلاح، وقد سقط في أوّل قياسٍ له.**
        //
        // الخدماتُ تقرأ الرقمَ من القاعدة ثمّ تُطبّعه ثانية. فإن لم يكن
        // التطبيعُ متعادياً، خرج رقمٌ ثالثٌ لا يطابق المخزَّنَ ولا المُدخَل
        // — **فيصير الحسابُ غيرَ قابلٍ للبلوغ بعد إنشائه**.
        //
        // وقِيس فوُجد `966501234567` المخزَّنُ يصير `967966501234567`.
        // ══════════════════════════════════════════════════════════════
        $once = Phone::canonical($input);

        $this->assertSame($once, Phone::canonical($once),
            "التطبيعُ ليس متعادياً على «{$input}» — فكلُّ قراءةٍ تُنتج رقماً ثالثاً");
    }

    public static function everyShape(): array
    {
        return array_map(fn ($v) => [$v], [
            '+967771000001', '771000001', '0771000001', '967771000001',
            '00967771000001', '+966501234567', '+201001234567',
            '+15551234567', '+447700900123', '2234567', '+9995551234',
            'nulL771000001',
        ]);
    }

    // ══════════════════════════════════════════════════════════════════
    //  ④ والمفتاحُ المُصرَّحُ به أصدقُ من أيّ استنتاج
    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function a_declared_dial_code_wins(): void
    {
        $this->assertSame('966501234567', Phone::canonical('501234567', '+966'));
        $this->assertSame('967771000001', Phone::canonical('771000001', '+967'));
    }

    /** @test */
    public function a_declared_code_is_not_doubled_when_the_number_already_has_it(): void
    {
        // **والتطبيقُ يرسل `dial_country_code . phone`.** فتضعيفُ المفتاح
        // ينتج رقماً لا وجودَ له — وهو عطلٌ صامتٌ من الصنف نفسِه.
        $this->assertSame('966501234567', Phone::canonical('+966501234567', '+966'));
        $this->assertSame('967771000001', Phone::canonical('967771000001', '967'));
    }

    // ══════════════════════════════════════════════════════════════════
    //  ⑤ والقطعُ الأعمى للمفتاح انتهى
    // ══════════════════════════════════════════════════════════════════

    /** @test */
    public function the_national_part_is_cut_at_the_real_dial_code(): void
    {
        // كان `substr($c, 3)` — **ثلاثةُ محارفَ عمياءَ**. ومفاتيحُ الدول
        // من محرفٍ إلى ثلاثة، فكان يقطع رقمَ أمريكا من نصفه.
        $this->assertSame('771000001', Phone::national('+967771000001'));
        $this->assertSame('501234567', Phone::national('+966501234567'));
        $this->assertSame('5551234567', Phone::national('+15551234567'));
        $this->assertSame('1001234567', Phone::national('+201001234567'));
    }

    /** @test */
    public function variants_of_a_foreign_number_never_contain_a_yemeni_form(): void
    {
        // **و`variants()` هي ما يبحث به المنتجُ كلُّه.** فصيغةٌ يمنيّةٌ
        // مزيّفةٌ فيها تعني حساباً يُنشأ ولا يُبلَغ — أو أسوأ: يُطابَق
        // حسابٌ ليس هو.
        $v = Phone::variants('+966501234567');

        $this->assertContains('966501234567', $v);

        foreach ($v as $form) {
            $this->assertStringNotContainsString('967966', $form,
                'صيغةٌ يمنيّةٌ مزيّفةٌ في بدائل رقمٍ سعوديّ');
        }
    }

    /** @test */
    public function an_empty_phone_is_not_turned_into_a_country_code(): void
    {
        // **وغيابُ الرقم ليس رقماً.** كان الفراغُ يُنتج `967` — قيمةً
        // تدخل البحثَ فتطابق ما لا يجوز أن تطابقه. (القاعدة السابعة.)
        $this->assertSame('', Phone::canonical(''));
        $this->assertSame('', Phone::canonical('   '));
        $this->assertSame([], Phone::variants(''));
    }

    /** @test */
    public function an_unknown_dial_code_is_left_alone_not_forced_home(): void
    {
        // **وجدولٌ ناقصٌ يجب ألّا يُعيد إنتاج العطل نفسِه.** فما جُهل
        // مفتاحُه يُترك كما وصل، ولا يُردّ إلى اليمن.
        $this->assertSame('9995551234', Phone::canonical('+9995551234'));
        $this->assertStringStartsNotWith('967', Phone::canonical('+9995551234'));
    }
}
