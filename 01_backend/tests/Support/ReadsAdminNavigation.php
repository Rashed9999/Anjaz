<?php

namespace Tests\Support;

use App\Models\User;

/**
 * AMIAL-ADMIN-NAV-SURFACE-001 — **سطحُ التنقّل يُقرأ من موضعٍ واحد.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ما وقع:** نقل صاحبُ المشروع خمسين وجهةً من الشريط الجانبيّ إلى صفحة
 * «مساحة العمل» بتبويبات (`@if(false)` يلفّ المجموعاتِ في `_sidebar`،
 * وتعريفُها بقي مرجعاً للتغطية). **وهي إعادةُ تنظيمٍ سليمة**: خمسون
 * رابطاً في عمودٍ واحدٍ يُوجَد بالتمرير لا بالمعرفة.
 *
 * **فسقطت خمسةُ حرّاسٍ لا لأنّ شيئاً انكسر، بل لأنّها تسأل عن الموضع:**
 * «هل الرابطُ في `<aside>`؟». والمحروسُ ليس ذلك — بل **هل يبلغ المديرُ
 * اللوحةَ من مكانٍ يمرّ به؟** (القاعدة ١٢.)
 *
 * وهو نفسُ الدرس المكتوب في `PlatformRoleEnforcementTest`: **تُقاس
 * الوجهةُ لا التسمية ولا الموضع** — وحارسٌ يمنع إعادةَ تنظيمٍ أفضل
 * يُعطَّل ثمّ لا يحرس شيئاً.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولمَ موضعٌ واحد:** لأنّ الوجهات انتقلت مرّةً وستنتقل ثانية. فلو نُسخ
 * استخراجُ الروابط في كلّ ملفّ، لسقطت كلُّها ثانيةً مع أوّل نقلة — وهو
 * **نفسُ العطل**: حقيقةٌ واحدةٌ في مواضعَ متفرّقة.
 *
 * **وأخطرُ ما كشفه هذا النقل:** صفحةُ مساحة العمل كانت تردّ ٥٠٠ على
 * الإنتاج (خطأُ تحليلٍ في Blade). أي أنّ **الوجهاتِ الخمسين كلَّها صارت
 * غيرَ قابلةٍ للوصول دفعةً واحدة**، والشريطُ الجانبيُّ لا يعرضها.
 * ولذلك يشترط كلُّ استخراجٍ هنا `assertOk()` على الصفحتين: **سطحُ تنقّلٍ
 * لا يُفتح ليس سطحَ تنقّل.**
 */
trait ReadsAdminNavigation
{
    /** روابطُ الشريط الجانبيّ وحده — البابُ السريع. */
    protected function sidebarLinks(User $admin): array
    {
        $html = $this->actingAs($admin, 'user')
            ->get('/admin')->assertOk()->getContent();

        preg_match('~<aside[^>]*amial-sidebar.*?</aside>~s', $html, $m);

        $this->assertNotEmpty($m, 'تعذّر العثور على الشريط الجانبي في الصفحة');

        return $this->hrefsIn($m[0]);
    }

    /**
     * روابطُ بطاقات «مساحة العمل» — حيث تعيش الوجهاتُ اليوم.
     *
     * **وتُقتطع البطاقاتُ وحدَها.** فالصفحةُ ترث القالبَ الأمّ ومعه
     * الشريطُ الجانبيّ، فقراءةُ الصفحة كلّها تخلط السطحين: ظهرت
     * `ops/roles` و`2fa` «مكرّرتين» وهما مرّةً في كلٍّ — **وهو بالضبط
     * الإنذارُ الكاذب الذي يُعوِّد القارئَ تجاهلَ اللافتة يومَ تصدق.**
     */
    protected function workspaceLinks(User $admin): array
    {
        $html = $this->workspaceHtml($admin);

        // من أوّل البطاقات إلى نهاية `<main>`: والشريطُ الجانبيّ قبله في
        // القالب (`<aside>` ثمّ `<main>`)، فلا يدخل في الاقتطاع.
        preg_match('~<div class="tab-content">.*?</main>~s', $html, $m);

        $this->assertNotEmpty($m, 'تعذّر العثور على بطاقات مساحة العمل');

        // **وصفُّ «الأكثر استخداماً» سطحٌ مستقلٌّ يُقتطَع** — بابٌ سريعٌ
        // إلى وجهةٍ لها بيتُها في التبويبات، كما الشريطُ الجانبيّ تماماً.
        // ويُفحَص وحدَه في `frequentLinks()`، فلا يسقط من الحراسة.
        $slice = $m[0];
        $cut = strpos($slice, 'id="ws-frequent"');

        return $this->hrefsIn($cut === false ? $slice : substr($slice, 0, $cut));
    }

    /** روابطُ «الأكثر استخداماً» وحدَها — سطحٌ ثالثٌ يُفحص كغيره. */
    protected function frequentLinks(User $admin): array
    {
        $html = $this->workspaceHtml($admin);

        if (! preg_match('~<div class="row g-2" id="ws-frequent">.*?</main>~s', $html, $m)) {
            return [];
        }

        return $this->hrefsIn($m[0]);
    }

    protected function workspaceHtml(User $admin): string
    {
        return $this->actingAs($admin, 'user')
            ->get(route('admin.amial.workspace.index'))
            ->assertOk()   // ٥٠٠ هنا = خمسون وجهةً تسقط دفعةً واحدة
            ->getContent();
    }

    /**
     * **كلُّ ما يبلغه المديرُ من مكانٍ يمرّ به** — الشريطُ ومساحةُ العمل.
     *
     * وهذا هو المقياسُ الذي تحرسه اختباراتُ الوصول: لا يعنيها في أيّ
     * الصفحتين وُجد الرابط، بل أن يُوجَد في إحداهما.
     */
    protected function reachableAdminLinks(User $admin): array
    {
        return array_merge($this->sidebarLinks($admin), $this->workspaceLinks($admin));
    }

    /**
     * **الوجهاتُ كما تُعلَن في المصدر الحيّ** — `[التسمية، المسار، الصلاحيّة]`.
     *
     * ══════════════════════════════════════════════════════════════════
     * **ولمَ من `workspace` لا من `_sidebar`:** بقي في `_sidebar` تعريفُ
     * الوجهات الأربع والخمسين داخل `@if(false)` «مرجعاً للتغطية»، وهو
     * **نصٌّ لا يراه مستعملٌ أبداً**. وقد شاخ فعلاً: ثلاثُ صلاحيّاتٍ فيه
     * تخالف ما يطلبه مسارُها، **وقد صُحّحت في مساحة العمل**.
     *
     * فكان حارسُ «الرابط يطلب ما تطلبه صفحتُه» يُبلّغ عن ثلاثة أعطالٍ
     * **لا وجودَ لها عند أيّ مستعمل**، ويصمت عن مساحة العمل التي تحمل
     * الروابطَ فعلاً. **وحارسٌ يقرأ نسخةً ميّتةً يُنذر كاذباً ويعمى صادقاً.**
     *
     * (وقِيس الفارقُ قبل هذا القرار: ٥٤ وجهةً في المرجع، ٥٥ في مساحة
     * العمل، و**صفرُ وجهةٍ ضاعت** في النقل — فالنقلُ كان كاملاً.)
     * ══════════════════════════════════════════════════════════════════
     *
     * @return list<array{0:string,1:string,2:?string}>
     */
    protected function declaredNavigationItems(): array
    {
        $src = file_get_contents(resource_path(
            'views/admin-views/amial/ops/workspace.blade.php'));

        preg_match_all(
            "~\[\s*'([^']{2,80})'\s*,\s*route\('([^']+)'\)[^,]*,\s*(null|'[^']+')~",
            $src, $m, PREG_SET_ORDER);

        $this->assertNotEmpty($m, 'تعذّر قراءة وجهات مساحة العمل من مصدرها');

        return array_map(
            static fn (array $x): array => [$x[1], $x[2], $x[3] === 'null' ? null : trim($x[3], "'")],
            $m);
    }

    /**
     * الفاصل `~` لا `#`: الأخير يظهر داخل صنف المحارف `[^"#]` فيُنهي
     * التعبير قبل أوانه — «Unknown modifier». (سقط اختبارٌ عليه فعلاً.)
     */
    private function hrefsIn(string $html): array
    {
        preg_match_all('~<a[^>]+href="([^"#]+)"~', $html, $hrefs);

        return array_values(array_filter(
            $hrefs[1],
            // روابطُ المطاوي (`#amial-grp-0`) ليست وجهات — تُستبعد.
            static fn (string $h): bool => $h !== '' && ! str_starts_with($h, '#'),
        ));
    }
}
