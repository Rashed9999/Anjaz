{{-- AMIAL-CLOCK-001 — حارسُ الساعة.

     ══════════════════════════════════════════════════════════════════
     **العطل الذي أدخل هذا الملفّ.** تأخّرت ساعةُ خادم الإنتاج خمساً
     وثلاثين ساعة. فظهر العطل في مكانٍ لا يدلّ عليها: صفحةُ دخول تُفتح
     ٢٠٠ بلا شكوى، ثمّ ٤١٩ بيضاء عند أوّل إرسال — لأنّ كوكي الجلسة تحمل
     انتهاءً في الماضي بنظر المتصفّح فيرميها لحظةَ وصولها.

     **والدخول أهونُ ما تكسره ساعةٌ خاطئة.** فالتسوية اليوميّة نافذتُها
     ٢٢:٠٠–٢٤:٠٠، وحسابُ اليوم من `whereDate(created_at)`. فخادمٌ يظنّ
     نفسه في يومٍ مضى يقفل اليوم الخطأ، ويحسب حركةَ يومٍ في يومٍ آخر،
     ويختم الورديّات والإيصالات بأوقاتٍ لم تقع. وذلك فسادُ بيانات
     يُكتشف بعد أسابيع، لا شاشةٌ تُعاد.

     ══════════════════════════════════════════════════════════════════
     **ولماذا يُقاس في المتصفّح؟** لأنّ الخادم لا يستطيع أن يكشف خطأ
     ساعته بنفسه: يقارن وقته بوقته فيصحّ دائماً. والمتصفّح وحده يحمل
     مرجعاً مستقلّاً — ساعةَ الهاتف المضبوطة تلقائياً من شبكة المشغّل.

     ولا يُنادَى فيه خادمُ وقتٍ خارجيّ: شبكةٌ محجوبة تجعل الحارس يصمت
     أو يكذب، و«غير معروف» ليس صفراً.

     ══════════════════════════════════════════════════════════════════
     **ووقتُ الخادم في سِمةٍ لا داخل الجافاسكربت.** كان `var ms = {{ … }}`
     فأمسكه فحصُ الضغط: قالبٌ يُقرأ بلا مُصيِّر Blade يُنتج `var ms = ;`
     — أي ملفّاً لا يُحلَّل. والسِمةُ تُقرأ نصّاً في الحالين، ويُفحص
     الرقم قبل استعماله فلا يصرخ الحارس على غياب. --}}
<div id="clock-guard" data-server-ms="{{ now()->valueOf() }}" style="display:none"></div>

<script nonce="{{ request()->attributes->get('csp_nonce') }}">
(function () {
    var el = document.getElementById('clock-guard');
    if (!el) return;

    var serverMs = Number(el.dataset.serverMs);

    // **رقمٌ غائبٌ ليس فرقاً هائلاً.** ولولا هذا الفحص لأنتج غيابُ السِمة
    // `NaN` أو صفراً — فيصرخ الحارس «الساعة متأخّرة ٤٩٠٠٠٠ ساعة» على
    // خادمٍ سليم، وأوّل إنذارٍ كاذب يُعلّم الناس تجاهل الإنذارات.
    if (!isFinite(serverMs) || serverMs <= 0) return;

    var driftMin = (Date.now() - serverMs) / 60000;
    var abs = Math.abs(driftMin);

    // عشر دقائق: أكبر من أيّ تأخّر شبكةٍ معقول، وأصغر من أن يُخطئ يوماً.
    if (abs <= 10) return;

    var hours = abs / 60;
    var amount = hours >= 1 ? Math.round(hours) + ' ساعة' : Math.round(abs) + ' دقيقة';
    var dir = driftMin > 0 ? 'متأخّرة' : 'متقدّمة';

    el.style.display = 'block';
    el.style.cssText += ';background:#fef3c7;border-right:5px solid #d97706;'
        + 'padding:14px 16px;border-radius:10px;margin:0 0 16px;line-height:1.9;font-size:14px';

    el.innerHTML =
        '<strong>⚠️ ساعةُ الخادم ' + dir + ' نحو ' + amount + ' عن الوقت الحقيقيّ.</strong>'
        + '<div style="margin-top:6px">وهذا ليس عطلاً في العرض: نافذةُ التسوية اليوميّة'
        + ' (١٠–١٢ ليلاً) تُحسب بساعة الخادم، وحركةُ «اليوم» تُجمَع بتاريخه،'
        + ' وأوقاتُ الورديّات والإيصالات تُختم به.</div>'
        + '<div style="margin-top:6px">🛠️ اضبط ساعة الخادم قبل أيّ تسويةٍ أخرى'
        + ' — <code style="direction:ltr;display:inline-block">timedatectl set-ntp true</code>'
        + ' على الخادم، أو أعِد تشغيله.</div>';
})();
</script>
