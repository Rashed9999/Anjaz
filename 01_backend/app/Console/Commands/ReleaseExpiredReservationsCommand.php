<?php

namespace App\Console\Commands;

use App\Services\Retail\StockReservationService;
use Illuminate\Console\Command;

/**
 * AMIAL-RETAIL-RESERVATION-002 — **مهلةٌ مكتوبةٌ لا تنتهي أبداً.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ما قِيس:**
 *
 *     holdForSale     → يُنادى ✓  (يحجز بـ`expires_at`)
 *     consumeForSale  → يُنادى ✓  (عند نجاح الدفع)
 *     releaseForSale  → **صفرُ مُنادٍ**
 *     releaseExpired  → **صفرُ مُنادٍ**
 *
 * والتعليقُ عند نقطة الحجز في `CashierService` يَعِد بنصّه: «الحجزُ
 * يُبقيها موجودةً وغيرَ متاحة، حتّى ينجح الدفعُ **أو تنتهي المهلة**».
 * **والمهلةُ لا تنتهي**: `expires_at` عمودٌ يُكتَب ولا يُقرأ.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والأثرُ نزفٌ صامتٌ في مخزون التاجر.**
 *
 * الدفعُ بأميال باي غيرُ متزامن: يُنشأ الحجزُ ثمّ يُنتظَر. فإن هجر
 * الزبونُ السلّة، أو انقطعت شبكتُه، أو سقط الدفع — **يبقى الصفُّ `HELD`
 * إلى الأبد**. و`computedReserved` تطرح المحجوزَ من المتاح، فالمتاحُ
 * ينكمش مع كلّ سلّةٍ مهجورة.
 *
 * ولا خطأَ في أيّ سجلّ، ولا شاشةَ تقول لماذا: يرى صاحبُ المحطّة «٠ متاح»
 * والرفُّ ملآن. **وهذا في تجربةٍ بألفَي مستخدمٍ نزفٌ يوميّ.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولمَ أمرٌ مجدوَلٌ لا وسيطة:** الحجزُ ينتهي بمرور الوقت لا بطلبٍ
 * يصل — وسلّةٌ مهجورةٌ لا يفتحها أحدٌ ثانيةً بحكم كونها مهجورة. فحاجزٌ
 * يعتمد على طلبٍ قادمٍ لا يُطلَق على الحالة التي وُجد لها.
 *
 * يظهر في : لا شاشة — أمرٌ مجدوَلٌ كلَّ خمس دقائق. **وأثرُه يظهر** في
 * لوحة التاجر ← المخزون ← «المتاح»، وفي مركز الأعطال إن سقط.
 */
class ReleaseExpiredReservationsCommand extends Command
{
    protected $signature = 'amial:release-expired-reservations {--limit=500 : سقفُ ما يُفكّ في الجولة}';

    protected $description = 'فكُّ حجوزات المخزون التي انتهت مهلتُها — وبلاه لا تنتهي مهلةٌ أبداً';

    public function handle(StockReservationService $reservations): int
    {
        $limit = max(1, (int) $this->option('limit'));

        try {
            $freed = $reservations->releaseExpired($limit);
        } catch (\Throwable $e) {
            // **وسقوطٌ صامتٌ هنا يُعيد العطلَ نفسَه بثوبٍ آخر.** الأمرُ
            // يجري بلا عينٍ عليه، فإن سقط كلَّ ليلةٍ لم يعلم أحد.
            app(\App\Services\OpsAlertService::class)->note(
                'retail.reservations.release_failed',
                'تعذّر فكُّ حجوزات المخزون المنتهية',
                'المتاحُ في لوحة التاجر ينكمش مع كلّ سلّةٍ مهجورة. السبب: '
                    . $e->getMessage(),
            );

            $this->error('تعذّر الفكّ: ' . $e->getMessage());

            return self::FAILURE;
        }

        // **ولا يُطبَع سطرٌ على صفر.** جولةٌ لا تجد شيئاً هي الحالُ السويّة،
        // وطباعتُها كلَّ خمس دقائق تُغرق السجلَّ فتُخفي ما يُقرأ.
        if ($freed > 0) {
            $this->info("فُكَّ {$freed} حجزاً منتهيَ المهلة");
        }

        return self::SUCCESS;
    }
}
