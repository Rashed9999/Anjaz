<?php

namespace App\Support;

/**
 * AMIAL-APP-URL-SANITIZE-001 — `APP_URL` يُنظَّف ويُتحقَّق منه قبل أن يُقرأ.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **العطل الذي أدخل هذا:**
 *
 *     #19 13.36 In Request.php line 352:
 *     #19 13.36   Invalid URI: Scheme is malformed.
 *     #19 ERROR: process "composer install --no-dev …" exit code: 1
 *     Deployment failed.
 *
 * ستّ دقائق بناءٍ ضاعت. والرسالة **لا تذكر `APP_URL` إطلاقاً** ولا تقول
 * أيّ قيمةٍ أفسدته — فتبدو عطلاً في المشروع أو في composer.
 *
 * والسلسلة كاملةً:
 *
 *     APP_URL → config('app.url') → SetRequestForConsole
 *             → Request::create() → strcspn في Symfony
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وما ظننتُه أوّلاً كان خطأً.** ظننتُ علامتَي التنصيص السببَ، فقِستُ
 * فوجدتُ Laravel يجرّدها بنفسه في `Env::get`. والقياس على المسار الحقيقيّ
 * (‏`artisan package:discover` بقيمٍ مختلفة) أعطى ثلاثةً فقط:
 *
 *   | القيمة                          | النتيجة                    |
 *   |---------------------------------|----------------------------|
 *   | `APP_URL=https://amialpay.com`  | Scheme is malformed ← الأرجح |
 *   | ` https://amialpay.com`         | Scheme is malformed        |
 *   | `https://amialpay.com ` (نهاية) | Host is malformed          |
 *   | `"https://amialpay.com"`        | ✓ يمرّ (Laravel يجرّدها)   |
 *   | `https:/amialpay.com`           | ✓ يمرّ (ثمّ تُبنى روابط خاطئة) |
 *
 * والأوّل هو ما يقع في لوحات النشر: حقلا «المفتاح» و«القيمة» منفصلان،
 * فيُلصق السطر كلّه في حقل القيمة.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والمنهج هنا: يُقصّ الواضح، ويُرفَض الباقي بصوتٍ مفهوم.**
 *
 * لا يُخمَّن ما وراء ذلك. فعنوانٌ خاطئٌ يُصلَّح سرّاً أسوأ من الفشل: تُبنى
 * روابط الصور والإيصالات إلى مضيفٍ آخر، وتظهر مكسورةً **بلا خطأٍ في أيّ
 * سجلّ**. وأصعبُ عطلٍ يُشخَّص هو الذي لا يشتكي.
 *
 * فالفشل يبقى فشلاً — لكنّه يقول ما القيمة وما المتوقَّع وأين تُصلَح.
 */
class AppUrl
{
    /** يُستعمل حين لا يُضبط المتغيّر أصلاً. */
    public const FALLBACK = 'http://localhost';

    /**
     * محارفٌ تُقصّ من الطرفين: بيضاء ظاهرة، وبيضاء **غير مرئيّة**.
     *
     * وهذه الثانية هي التي أطالت التشخيص: حقلُ Coolify يعرض
     * `https://amialpay.com` سليماً تماماً، ومسافةٌ غير فاصلة (U+00A0)
     * أو علامةُ ترتيبٍ لصقت من صفحةِ ويب لا تظهر في أيّ صورة. فتُقصّ
     * صراحةً — ولا واحدةٌ منها تكون في عنوانٍ صحيح أبداً.
     */
    private const TRIM = " \t\n\r\0\x0B\"'"
        . "\u{00A0}"   // مسافة غير فاصلة
        . "\u{200B}\u{200C}\u{200D}"  // عرضٌ صفريّ
        . "\u{200E}\u{200F}"          // علامتا الاتّجاه (شائعتان مع العربيّة)
        . "\u{2028}\u{2029}"          // فاصلا سطرٍ وفقرة
        . "\u{FEFF}";                 // علامة ترتيب البايتات

    /**
     * يقصّ ما لا يكون في عنوانٍ صحيح أبداً.
     *
     * الفراغات وعلامات التنصيص (حزامُ أمانٍ ثانٍ بعد `Env::get`) والشرطة
     * المائلة الأخيرة، وبادئة `APP_URL=` المكرّرة على نفسها.
     */
    public static function clean(?string $raw): string
    {
        $v = trim((string) $raw, self::TRIM);

        // البادئة المكرّرة: `APP_URL=https://…` مُلصَقاً في حقل القيمة.
        // وهي قصٌّ لا تخمين — الاسم يساوي المفتاح نفسه حرفاً بحرف.
        if (preg_match('/^APP_URL\s*=\s*/i', $v)) {
            $v = (string) preg_replace('/^APP_URL\s*=\s*/i', '', $v);
            $v = trim($v, self::TRIM);
        }

        return rtrim($v, '/');
    }

    /**
     * أهو عنوانٌ مطلقٌ صالحٌ على http أو https؟
     *
     * **ولا يُكتفى بـ`filter_var`**: هي تقبل `https:/host` بشرطةٍ واحدة —
     * وهي قيمةٌ تمرّ ثمّ تُنتج روابط مكسورةً بصمت. فيُفحص المضيف صراحةً.
     */
    public static function isValid(string $url): bool
    {
        $p = parse_url($url);

        return is_array($p)
            && in_array($p['scheme'] ?? '', ['http', 'https'], true)
            && ($p['host'] ?? '') !== ''
            && str_starts_with($url, ($p['scheme'] ?? '') . '://');
    }

    /**
     * يعرض المحارف غير المطبوعة كرموزٍ مرئيّة.
     *
     * **وهذه هي الفائدة كلّها.** رسالة Symfony عرضت العنوان فبدا سليماً
     * تماماً — وهو ما أطال التشخيص. فمسافةٌ أو علامةُ اتّجاهٍ لصقت من
     * صفحةِ ويب لا تُرى في أيّ رسالةٍ ولا في أيّ صورةِ شاشة، ولا في حقل
     * لوحة النشر نفسه. فتُطبَع بايتاً بايتاً.
     */
    public static function visualize(string $s): string
    {
        $out = '';

        foreach (preg_split('//u', $s, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $ch) {
            $cp = mb_ord($ch, 'UTF-8');

            // مطبوعٌ عاديّ (ASCII مرئيّ) يُترك كما هو.
            if ($cp !== false && $cp > 0x20 && $cp < 0x7F) {
                $out .= $ch;
                continue;
            }

            $out .= $cp === 0x20 ? '␠' : sprintf('⟨U+%04X⟩', (int) $cp);
        }

        return $out;
    }

    /**
     * القيمة التي تُسلَّم إلى `config('app.url')`.
     *
     * @throws \RuntimeException إن بقيت غير صالحةٍ بعد التنظيف.
     */
    public static function resolve(?string $raw): string
    {
        // غير مضبوطٍ أصلاً ⇒ الافتراضيّ. وهذا ليس خطأ ضبطٍ بل غيابُه.
        if ($raw === null || trim($raw, self::TRIM) === '') {
            return self::FALLBACK;
        }

        $clean = self::clean($raw);

        if ($clean === '') {
            return self::FALLBACK;
        }

        if (! self::isValid($clean)) {
            throw new \RuntimeException(
                "\n"
                . "══════════════════════════════════════════════════════\n"
                . " APP_URL غير صالح — والبناء يقف هنا عمداً.\n"
                . "══════════════════════════════════════════════════════\n"
                . " القيمة الحالية : [{$raw}]\n"
                . " بعد التنظيف    : [{$clean}]\n"
                . " المتوقَّع        : https://amialpay.com\n"
                . "\n"
                . " بايتاتها (لتظهر المحارف الخفيّة):\n"
                . "   " . self::visualize($raw) . "\n"
                . "\n"
                . " الأشيع: لصقُ السطر كلّه في حقل «القيمة».\n"
                . " حقل المفتاح: APP_URL   وحقل القيمة: https://amialpay.com\n"
                . " بلا مسافةٍ في البداية، وبلا تكرار الاسم داخل القيمة.\n"
                . "══════════════════════════════════════════════════════\n"
            );
        }

        return $clean;
    }
}
