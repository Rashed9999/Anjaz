<?php

namespace App\Support;

use Illuminate\Support\Str;

/**
 * AMIAL-DEMO-CREDENTIALS-001 — **كلمةُ مرورِ إدارةٍ منشورةٌ وتُعاد كلَّ نشرة.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ما قِيس، ولم يُفترَض:**
 *
 *     docker/entrypoint.sh:265-270
 *       if [ "$DB_OK" -eq 1 ]; then          ← الحارسُ الوحيد
 *           php artisan amial:ensure-demo
 *           php artisan amial:ensure-demo-staff
 *           php artisan amial:ensure-demo-merchants
 *
 * **لا شرطَ بيئةٍ إطلاقاً** — «القاعدةُ حيّة» وحدَها. فالأوامرُ تجري في
 * كلّ إقلاع حاويةٍ على الإنتاج، و`EnsureDemoStaff` يكتب:
 *
 *     admin@amialpay.com · 967777000001 · Pass@2026 · type=ADMIN · نشِط
 *     وكيل            · 967777900001 · Pass@2026
 *
 * والكلمةُ **مكتوبةٌ في المستودع**. ومن ملكها ملك اللوحةَ كلَّها: أرصدةَ
 * العملاء، والتجميدَ، وضبطَ الرسوم، وسجلَّ التدقيق.
 *
 * **وأسوأُ ما فيه أنّه يُعيد الضبط لا أنّه يُنشئ:** السطرُ
 * `$admin->password = Hash::make(self::PASSWORD)` يقع على حسابٍ **قائم**.
 * فلو غيّر صاحبُ المشروع الكلمةَ اليوم، **أعادها النشرُ غداً** — وهو لا
 * يعلم، ولا سطرَ في أيّ سجلٍّ يقول إنّها رُدَّت.
 *
 * والتعليقُ في الشيفرة يقول القصدَ صراحةً: «**«ضمان» يعني بيانات دخول
 * معلومة دوماً**» — قرارُ راحةٍ في التطوير، يعمل اليوم على الإنتاج.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولمَ لا تُحذَف الأوامر:** `EnsureDemoStaff` هو **مسارُ إنشاء الأدمن
 * الوحيد** خارج بذرةٍ محروسةٍ بـ`RUN_SEEDERS`. فحذفُه على قاعدةٍ جديدة
 * يترك المنصّةَ بلا بابِ إدارةٍ إطلاقاً — **وفقدُ الوصول أسوأ من كلمةٍ
 * معلومة**، وهو خطأٌ لا يُصلَح إلّا بيدٍ على القاعدة.
 *
 * فالقسمةُ ثلاثةٌ لا اثنان:
 *
 *   · **إنشاءٌ عند الغياب**  — يبقى دائماً، وإلّا وقع القفلُ التامّ
 *   · **كلمةٌ معلومة**       — للتطوير، وفي الإنتاج بموافقةٍ صريحةٍ فقط
 *   · **إعادةُ ضبطٍ لقائم**  — **تتوقّف في الإنتاج**، وهي موضعُ الضرر
 *
 * وفي الإنتاج بلا موافقة: الكلمةُ من `AMIAL_BOOTSTRAP_ADMIN_PASSWORD` إن
 * ضُبطت، وإلّا **تُولَّد قويّةً وتُطبع مرّةً واحدة** في سجلّ النشر —
 * فيبقى البابُ موجوداً ولا يكون معلوماً لأحدٍ سوى من يقرأ السجلّ.
 *
 * @see \Tests\Feature\DemoCredentialsGuardTest
 */
class DemoAccountPolicy
{
    /** المفتاحُ الذي يفتح السلوكَ القديمَ كاملاً — للعرض والتطوير. */
    public const OPT_IN = 'AMIAL_ALLOW_DEMO_ACCOUNTS';

    /**
     * أيُسمح بكلمةِ مرورٍ معلومةٍ مكتوبةٍ في المستودع؟
     *
     * **خارج الإنتاج: نعم** — وهو ما يجعل التطويرَ والعرضَ ممكنين.
     * **وفي الإنتاج: لا، إلّا بموافقةٍ صريحةٍ في البيئة.**
     */
    public static function knownPasswordAllowed(): bool
    {
        if (! app()->environment('production')) {
            return true;
        }

        return filter_var(env(self::OPT_IN, false), FILTER_VALIDATE_BOOLEAN);
    }

    /**
     * أتُعاد كلمةُ مرورِ حسابٍ **قائم**؟
     *
     * **وهذا هو موضعُ الضرر بعينه.** الإنشاءُ عند الغياب لا يضرّ أحداً —
     * وإعادةُ الضبط تمحو تغييراً متعمَّداً من صاحب المشروع، في كلّ نشرة،
     * بصمت.
     */
    public static function mayResetExisting(): bool
    {
        return self::knownPasswordAllowed();
    }

    /**
     * كلمةُ المرور التي يُنشأ بها حسابٌ **غائب**.
     *
     * @param  string  $known  الكلمةُ المعلومةُ المكتوبةُ في الأمر.
     * @param  string  $envKey مفتاحُ بيئةٍ يسمح لصاحب المشروع بتعيينها.
     */
    public static function passwordForNewAccount(string $known, string $envKey): string
    {
        if (self::knownPasswordAllowed()) {
            return $known;
        }

        $configured = trim((string) env($envKey, ''));

        if ($configured !== '') {
            return $configured;
        }

        // **ومولَّدةٌ خيرٌ من معلومة.** تُطبع مرّةً في سجلّ النشر، ولا
        // تُكتب في قاعدةٍ ولا ملفّ — فمن فاته السجلُّ يستعيدها بالمسار
        // العاديّ، ولا يبقى بابٌ مفتوحٌ للعالم.
        return Str::password(24, symbols: false);
    }

    /**
     * ما يُطبع بدل الكلمة — **فسجلُّ النشر يُقرأ ويُشارَك**.
     *
     * ولا تُطبع الكلمةُ المولَّدةُ إلّا حين لا يعرفها أحدٌ غيرُ هذا السطر.
     */
    public static function describe(?string $password, string $envKey): string
    {
        // **ولا يُطبَع سرٌّ لم يُكتَب.** حسابٌ قائمٌ لم تُعَد كلمتُه —
        // فطباعةُ المعلومة هنا تقول للقارئ إنّها تعمل، وهي لا تعمل.
        if ($password === null) {
            return '(لم تُغيَّر — الحسابُ قائمٌ منذ قبل)';
        }

        if (self::knownPasswordAllowed()) {
            return $password;
        }

        return trim((string) env($envKey, '')) !== ''
            ? '«المضبوطة في ' . $envKey . '»'
            : $password . '   ← مولَّدة، احفظها الآن أو اضبط ' . $envKey;
    }

    /**
     * سببُ التخطّي، يُقال صراحةً — **وصمتٌ في سجلّ النشر يُقرأ نجاحاً**.
     */
    public static function skipNotice(string $what): string
    {
        return "⏭  {$what}: لم تُعَد كلمةُ المرور — الإنتاجُ بلا "
            . self::OPT_IN . '=true. (الحسابُ قائمٌ ولم يُمسّ.)';
    }

    // ══════════════════════════════════════════════════════════════════
    // AMIAL-DEMO-MONEY-001 — **ومالٌ يُسَكّ في كلّ إقلاعٍ على الإنتاج.**
    //
    // سأل صاحبُ المشروع: «كلّ محافظ التجّار فيها ١٠٠ ألف — من أين أتت؟».
    // فقِيس، ولم يُفترَض:
    //
    //   EnsureDemoMerchants::ensureWallet()  →  current_balance = 100000
    //   EnsureDemoStaff                      →  500000 (وكيل)
    //   EnsureDemoUsers                      →  50000 · 10000 (عملاء)
    //   docker/entrypoint.sh:299-307         →  الثلاثةُ في **كلّ إقلاع**
    //
    // **وهي في الدفتر، وهذا أدقُّ ممّا يبدو:** `EMoneyObserver::created`
    // يكتب قيداً متوازناً `OPENING_BALANCE` (حقوق) مديناً ↔ محفظةَ
    // المستخدم دائناً. فالمصالحةُ تُخرج فرقاً صفراً — **لا انحرافَ
    // إطلاقاً**. لكنّ توازنَ القيد ليس مشروعيّةَ المال: حسابُ الافتتاح
    // معناه «مالٌ وُجد قبل الدفتر»، ولا أحدَ أودعه. فهي **التزامٌ على
    // المنصّة بلا مقابل**، وتدخل «إجماليَّ أرصدة التجّار» في مركز
    // السيطرة الماليّة كأنّها مالُ تاجرٍ حقيقيّ.
    //
    // **وثلاثةُ حدودٍ قِيست ولا تُخمَّن:**
    //   ① `firstOrCreate` ⇒ **لا تتراكم**. أُعيد الأمرُ مرّتين فبقي
    //      الرصيدُ ١٠٠٠٠٠ وقيدُ الافتتاح **واحداً**.
    //   ② التاجرُ الحقيقيُّ يولد بصفر (`FinancialGuardService`) —
    //      فالستّةُ الديمو وحدَهم.
    //   ③ ولا بابَ خروجٍ ذاتيّ: `send-money`/`cash-out` تردّان ٤٠٣
    //      لنوع ٣، والتسويةُ إداريّة. **فهي محبوسةٌ لا مسروقة.**
    //
    // فالحدُّ هو الحدُّ نفسُه الذي حكم كلمةَ المرور: **الإنشاءُ عند
    // الغياب يبقى، والسَّكُّ في الإنتاج يقف** — إلّا بموافقةٍ صريحة.
    // ══════════════════════════════════════════════════════════════════

    /** رصيدٌ يُملى صراحةً بدل المكتوب في الأمر. */
    public const WALLET_ENV = 'AMIAL_DEMO_WALLET_BALANCE';

    /**
     * الرصيدُ الذي تُولَد به محفظةٌ تجريبيّة.
     *
     * **وصفرٌ ليس تعطيلاً للحساب**: الحسابُ يُنشأ ويُدخَل إليه كما كان،
     * وحدَه المالُ لا يُسَكّ. ومن أراده في الإنتاج قاله في البيئة —
     * **فما يُملى يُراجَع، وما يقع بالصمت لا يُراجَع.**
     */
    public static function seededWalletBalance(string $known): string
    {
        if (self::knownPasswordAllowed()) {
            return $known;
        }

        $configured = trim((string) env(self::WALLET_ENV, ''));

        if ($configured !== '' && is_numeric($configured)
            && bccomp($configured, '0', 4) >= 0) {
            return bcadd($configured, '0', 4);
        }

        return '0.0000';
    }

    /** أسُكّ مالٌ في هذا الإقلاع؟ — للسطر الذي يُطبع في سجلّ النشر. */
    public static function walletNotice(string $seeded, string $known): string
    {
        if (bccomp($seeded, $known, 4) === 0) {
            return "رصيد {$seeded}";
        }

        return "رصيد {$seeded} (بدل {$known} — الإنتاجُ بلا "
            . self::OPT_IN . '=true؛ لسَكِّه اضبط ' . self::WALLET_ENV . ')';
    }
}
