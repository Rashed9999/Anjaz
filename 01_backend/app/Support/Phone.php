<?php

namespace App\Support;

/**
 * AMIAL-PHONE-001 — توحيد صيغة الهاتف.
 *
 * كان في المشروع ثلاثة مطبّعات مختلفة (تسجيل يخزّن +967…، بعض الخدمات تُزيل رمز
 * الدولة، واتساب يُبقيه) → عدم تطابق يمنع التحويل/الدخول أحياناً. هذا المصدر
 * الموحّد الوحيد للحقيقة.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **AMIAL-PHONE-002 — والرقمُ الأجنبيُّ كان يُصنَع يمنيّاً بالقوّة.**
 *
 * **العطل، وقد أُثبت بالتشغيل قبل كتابة سطرٍ من العلاج:**
 *
 *     +967771000001  →  967771000001     ✓
 *     +966501234567  →  967966501234567  ✗
 *     +201001234567  →  967201001234567  ✗
 *     +15551234567   →  96715551234567   ✗
 *     +447700900123  →  967447700900123  ✗
 *
 * السطرُ الأخير كان `return '967' . $p;` بلا شرط: **كلُّ رقمٍ لا يبدأ بـ967
 * تُلصَق به 967**. فحقلُ `dial_country_code` في نموذج التسجيل يُملأ ثمّ
 * **يُرمى** — يبتلعه المطبِّعُ ويعيد بناءَ الرقم يمنيّاً.
 *
 * **وأثرُه أنّ العطلَ صامت:** الرقمُ الناتجُ صالحُ الشكل وكاذبُ المعنى.
 * فلا OTP يصل، ولا خطأَ في أيّ سجلّ، والمستعملُ يرى «أُرسل الرمز» ثمّ
 * لا يأتي شيء. **وأخطرُ منه أنّ `variants()` تبحث بهذا المشوَّه**: فرقمان
 * أجنبيّان قد يتصادمان، أو يتعذّر بلوغُ حسابٍ بعد إنشائه.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والعلاجُ لا يُخمِّن الدولة — يقرأ علامةً صريحة.**
 *
 * التخمينُ من الأرقام وحدَها **مستحيلٌ بلا لبس**: رقمُ هاتفٍ أرضيٍّ في عدن
 * يبدأ بـ`2`، ومفتاحُ مصرَ `20`. فمن خمّن قلبَ رقماً محلّيّاً إلى مصريّ.
 *
 * فالفاصلُ هو **`+` أو `00`** — وهما علامتا «هذا رقمٌ دوليّ» في كلّ
 * الأنظمة، وهما ما يرسله التطبيقُ أصلاً (`dial_country_code` + الرقم):
 *
 *   · بعلامةٍ دوليّة  ⇒ يُحترم مفتاحُه ولا تُلصَق 967 أبداً
 *   · بلا علامة       ⇒ رقمٌ وطنيٌّ يمنيّ (وهو كلُّ ما في القاعدة اليوم)
 *
 * **والتوافقُ الخلفيُّ شرطُ صحّة**: كلُّ ما هو مخزَّنٌ اليوم يمنيّ، وصيغتُه
 * الناتجةُ لا تتغيّر بحرفٍ واحد — وهو محروسٌ بالاختبار.
 *
 * **ومفتاحٌ غيرُ معروفٍ لا يُردّ إلى اليمن.** الجدولُ أدناه يخدم تقليمَ
 * الصفر الوطنيّ البادئ وحدَه؛ فإن جُهل المفتاحُ تُترك الأرقامُ كما هي —
 * **فجدولٌ ناقصٌ يجب ألّا يُعيد إنتاج العطل نفسِه.**
 */
final class Phone
{
    /** مفتاحُ الوطن — الافتراضيُّ لكلّ رقمٍ بلا علامةٍ دوليّة. */
    public const HOME = '967';

    /**
     * مفاتيحُ الاتّصال الدوليّ — **للتقليم لا للتخمين**.
     *
     * تُقرأ من الأطول إلى الأقصر لئلّا يبتلع `1` مفتاحَ `1868`. وليست
     * كاملةً ولا يلزم أن تكون: ما ليس فيها يُترك كما وصل.
     */
    private const DIAL_CODES = [
        // الجزيرة والخليج والجوار — الأكثرُ وروداً في هذا المنتج
        '967', '966', '968', '971', '973', '974', '965', '962', '970', '964',
        '963', '961', '249', '253', '252', '251', '20', '212', '213', '216',
        '218', '222',
        // ما يقصده المغتربون غالباً
        '44', '49', '33', '39', '31', '46', '47', '45', '41', '43', '32',
        '90', '7', '86', '91', '92', '60', '62', '63', '65', '66', '81',
        '82', '27', '234', '254', '255', '256', '20',
        // أمريكا الشماليّة — يُقرأ آخراً لأنّه أقصرُها
        '1',
    ];

    /**
     * الشكلُ القانونيّ: مفتاحُ الدولة + الرقمُ الوطنيّ — بلا `+` ولا `00`
     * ولا صفرٍ بادئٍ ولا رموز.
     *
     * `$dialCode` يُمرَّر حين يكون معلوماً من النموذج، **فهو أصدقُ من أيّ
     * استنتاجٍ من الأرقام**.
     */
    public static function canonical(string $phone, ?string $dialCode = null): string
    {
        $raw = trim($phone);

        // **العلامةُ تُقرأ قبل أن تُمحى.** وهي كلُّ الفرق بين رقمٍ دوليٍّ
        // ورقمٍ وطنيٍّ يشبهه.
        $isInternational = str_starts_with($raw, '+')
            || str_starts_with(preg_replace('/[\s\-\(\)]/', '', $raw) ?? '', '00');

        // إزالة الفراغات والرموز، ثمّ أيّ حرفٍ غير رقميّ (يرسل التطبيق
        // أحياناً بادئة «null» حين لا يُضبط رمز الدولة → nulL777…).
        $p = preg_replace('/\D/', '', $raw) ?? '';

        // **ولا رقمٌ من لا رقمَ له.** كان الفراغُ يُنتج `967` — مفتاحاً
        // بلا رقم. وهو ليس «رقماً يمنيّاً»، بل قيمةٌ تدخل البحثَ فتطابق
        // ما لا يجوز أن تطابقه، **وتكسر التعادي**: `967` تُقرأ ثانيةً
        // فتصير `967967`. (القاعدة السابعة: الغيابُ ليس قيمة.)
        if ($p === '') {
            return '';
        }

        if ($isInternational && str_starts_with($p, '00')) {
            $p = substr($p, 2);
        }

        // ── مفتاحٌ مُصرَّحٌ به من النموذج: أصدقُ ما لدينا ──────────────
        $declared = $dialCode === null ? null : preg_replace('/\D/', '', $dialCode);

        if ($declared !== null && $declared !== '') {
            // **ولا يُضاعَف المفتاحُ إن كان الرقمُ يحمله أصلاً.** التطبيقُ
            // يرسل `dial_country_code . phone`، فالتضعيفُ ينتج رقماً
            // لا وجودَ له — وهو عطلٌ صامتٌ من الصنف نفسِه.
            if (str_starts_with($p, $declared)) {
                $p = substr($p, (int) strlen($declared));
            }

            return $declared . ltrim($p, '0');
        }

        if ($isInternational) {
            return self::splitAtDialCode($p) ?? $p;
        }

        // ══════════════════════════════════════════════════════════════
        // **بلا علامة — والتطبيعُ يجب أن يكون متعادياً.**
        //
        // `canonical(canonical($x))` **يجب أن تساوي** `canonical($x)`،
        // وإلّا فكلُّ خدمةٍ تُطبّع رقماً مقروءاً من القاعدة تُنتج رقماً
        // ثالثاً لا يطابق شيئاً. وهذا وقع في أوّل قياسٍ لهذا الإصلاح:
        // `966501234567` المخزَّنُ صار `967966501234567` عند إعادة قراءته.
        //
        // **والفاصلُ طولُ الرقم الوطنيّ اليمنيّ**: تسعةُ أرقامٍ للجوّال
        // وأقلُّ للأرضيّ — فما زاد على ذلك وبدأ بمفتاحٍ معروفٍ رقمٌ
        // دوليٌّ مطبَّعٌ سلفاً، لا رقمٌ وطنيٌّ طويل.
        // ══════════════════════════════════════════════════════════════
        $bare = ltrim($p, '0');

        if (strlen($bare) <= self::HOME_NATIONAL_MAX) {
            return self::HOME . $bare;
        }

        if (str_starts_with($bare, self::HOME)) {
            return self::HOME . ltrim(substr($bare, 3), '0');
        }

        // رقمٌ طويلٌ بمفتاحٍ معروف: مطبَّعٌ سلفاً — يُعاد كما هو.
        $recovered = self::splitAtDialCode($bare);

        if ($recovered !== null) {
            return $recovered;
        }

        // **وما جُهل مفتاحُه وطال عن الوطنيّ يُترك كما هو.**
        //
        // فإلصاقُ 967 برقمٍ من عشرة أرقامٍ فأكثرَ لا يُنتج رقماً يمنيّاً —
        // ينتج رقماً لا وجودَ له، **ويكسر التعادي**: القراءةُ الثانية
        // تُلصقها ثانيةً فتُنتج رقماً ثالثاً. وقِيس فوُجد `+999…` يفعلها.
        return $bare;
    }

    /** أطولُ رقمٍ وطنيٍّ يمنيّ — الجوّالُ تسعةٌ والأرضيُّ أقلّ. */
    private const HOME_NATIONAL_MAX = 9;

    /** مفتاحٌ معروفٌ + وطنيٌّ مقلَّمٌ من صفره — أو `null` إن جُهل المفتاح. */
    private static function splitAtDialCode(string $digits): ?string
    {
        foreach (self::DIAL_CODES as $code) {
            if (! str_starts_with($digits, $code)) {
                continue;
            }

            $national = ltrim(substr($digits, (int) strlen($code)), '0');

            // مفتاحٌ بلا رقمٍ بعده ليس رقماً.
            return $national === '' ? null : $code . $national;
        }

        return null;
    }

    /** مفتاحُ الدولة كما قُرئ من الرقم القانونيّ. */
    public static function dialCodeOf(string $phone): string
    {
        return self::dialCodeIn(self::canonical($phone));
    }

    /** **يقرأ ولا يُطبّع** — فالتطبيعُ مرّتين هو العطلُ الذي يُتَّقى. */
    private static function dialCodeIn(string $canonical): string
    {
        foreach (self::DIAL_CODES as $code) {
            if (str_starts_with($canonical, $code)) {
                return $code;
            }
        }

        return '';
    }

    /** الرقم الوطني فقط (بلا مفتاح الدولة): 771000001. */
    public static function national(string $phone): string
    {
        // **ولا يُقتطع ثلاثةُ محارفَ عمياءً.** مفاتيحُ الدول من محرفٍ
        // إلى ثلاثة، والاقتطاعُ الأعمى كان يقطع رقمَ أمريكا من نصفه.
        $c = self::canonical($phone);
        $code = self::dialCodeIn($c);

        return $code === '' ? $c : substr($c, (int) strlen($code));
    }

    /**
     * كل الصيغ المكافئة — للبحث في عمود phone قد يكون مخزّناً بأيّ شكل تاريخي
     * (+967…، 00967…، 967…، وطني، أو وطني بصفر بادئ).
     *
     * @return string[]
     */
    public static function variants(string $phone): array
    {
        $c = self::canonical($phone);

        // **ولا يُبحَث بلا رقم.** بلا هذا يُنتج الفراغُ `['+', '00']`،
        // وهما يدخلان `whereIn` فيطابقان صفوفاً لا شأنَ لها بالطلب.
        if ($c === '') {
            return [];
        }

        $code = self::dialCodeIn($c);
        $nat = $code === '' ? $c : substr($c, (int) strlen($code));

        return array_values(array_unique(array_filter([
            $c,          // 967771000001
            '+' . $c,    // +967771000001
            '00' . $c,   // 00967771000001
            $nat,        // 771000001
            '0' . $nat,  // 0771000001
        ], fn ($v) => $v !== '' && $v !== '0')));
    }
}
