<?php

namespace App\Domain\Verticals;

use App\Support\Access\AccessConstants as A;

/**
 * AMIAL-VERTICAL-OOP-001 — **الصندوقُ المشترك، وما يخصّ كلَّ قطاعٍ وحدَه.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الثمنُ الذي دُفع، مقيساً:** منطقُ «صنف النشاط» متفرّقٌ في **ستّة
 * ملفّاتٍ و٧٨ موضعَ تفرّع** (`match` على `BIZ_*`)، والباقاتُ في ١٤٢
 * موضعاً. فإضافةُ قطاعٍ أو تعديلُه ستّةُ تعديلاتٍ متفرّقة — **ونسيانُ
 * واحدٍ لا يُسقط شيئاً بل يُنتج قطاعاً نصفَ مفتوح**:
 *
 *   • المطاعم: مُنحت «الطاولات» ولا «الطلبات» — فيرى صاحبُه طاولاتِه
 *     ولا يفتح طلباً، ويُردّ بـ«قطاع المطاعم متاح لحسابات المطاعم»
 *     وهو حسابُ مطعم.
 *   • الصيدليّةُ والبقالةُ بالقائمة نفسِها حرفاً بحرف في التطبيق.
 *   • `pharmacy_customers` تُباع في الباقة ولا نقطةَ نهايةٍ لها.
 *
 * وثلاثتُها عطلٌ واحد: **لا موضعَ واحدٌ يقول ما هذا القطاع.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والمشتركُ يُقاس لا يُفترَض.** قِيست القطاعاتُ الستّة:
 *
 *   المشتركُ بينها جميعاً        : `daily_reports` وحدَها
 *   وما يناله كلُّ تاجرٍ بدوره    : `roleBase(ROLE_MERCHANT)` — تسعُ ميزات
 *
 * **فـ`receipts` و`daily_reports` مكرَّرتان**: يمنحهما الدورُ لكلّ تاجر،
 * ثمّ يُعيد كلُّ قطاعٍ منحَهما في قائمته. وتكرارُ المنح ليس خطأً
 * سلوكيّاً اليوم — لكنّه **يجعل نزعَ إحداهما من الدور بلا أثر**، فيظنّ
 * من نزعها أنّه أغلقها وهي مفتوحةٌ من ستّة أبوابٍ أخرى.
 *
 * فصار المشتركُ في **صندوقٍ واحد** (`shared()`)، ولا يُعيده قطاعٌ.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **وأربعةُ أسئلةٍ يجيب عنها كلُّ قطاعٍ في ملفٍّ واحد:**
 *
 *   ① `code()`      رمزُه في القاعدة
 *   ② `nameAr()`    اسمُه للمستعمل — **مصدرٌ واحد**، فلا يختلف بين شاشتين
 *   ③ `own()`       ما يخصّه وحدَه ولا يعمل بدونه (النواة)
 *   ④ `paidDepth()` ما تبيعه الباقةُ فوق نواته
 *
 * **ولا يُسأل عن الأسعار ولا الحدود** — تلك للباقة لا للقطاع. وخلطُهما
 * هو ما جعل «كم منتجاً» جواباً في موضعين يفترقان.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والانتقالُ تدريجيٌّ لا انقلابيّ.** `AccessPresets` تبقى المدخلَ
 * العامّ وتسأل هذا السجلَّ — فلا تنكسر ٣٢٩٢ اختباراً في يوم، ولا
 * يُستبدَل عطلٌ معروفٌ بأعطالٍ مجهولة.
 */
abstract class MerchantVertical
{
    // ══════════════════════════════════════════════════════════════════
    //  الصندوقُ المشترك — ما يناله كلُّ تاجرٍ مهما كان نشاطُه
    // ══════════════════════════════════════════════════════════════════

    /**
     * **ما لا يُسأل عنه قطاعٌ لأنّه لكلّ التجّار.**
     *
     * والقائمةُ **مقيسةٌ من `roleBase(ROLE_MERCHANT)`** لا مخترَعة: هي
     * ما يمنحه الدورُ اليوم لكلّ تاجرٍ قبل أن يُعرف نشاطُه.
     *
     * **ولا يُعيدها قطاع.** من أعادها ظنّ أنّه يفتحها وهي مفتوحة، ومن
     * نزعها من هنا ظنّ أنّه أغلقها وهي مفتوحةٌ من قائمته.
     *
     * @return array<int,string>
     */
    final public static function shared(): array
    {
        return [
            // المحفظةُ والهويّة — تاجرٌ بلا محفظةٍ لا يقبض
            A::F_WALLET,
            A::F_PROFILE,
            A::F_NOTIFICATIONS,

            // حركةُ المال بين الحسابات — لا تخصّ نشاطاً دون آخر
            A::F_TRANSFER,
            A::F_RECEIVE,
            A::F_QR_PAY,

            // التوثيقُ والمستندُ والتقريرُ اليوميّ — بابُ كلّ نشاط
            A::F_MERCHANT_VERIFICATION,
            A::F_RECEIPTS,
            A::F_DAILY_REPORTS,
        ];
    }

    // ══════════════════════════════════════════════════════════════════
    //  ما يخصّ القطاعَ وحدَه
    // ══════════════════════════════════════════════════════════════════

    /** رمزُ القطاع كما يُخزَّن في `merchant_profiles.business_type`. */
    abstract public function code(): string;

    /**
     * اسمُه القصير كما يُعرَض — **ويُشتقّ ولا يُكتب**.
     *
     * ══════════════════════════════════════════════════════════════════
     * **كُتب هذا أوّلاً في كلّ قطاعٍ بيده، وكان خطأً.** فالمشروعُ فيه
     * `AccessConstants::BUSINESS_TYPE_LABELS` منذ زمن، ويستعمله خمسةُ
     * مواضع. فكتابةُ الاسم هنا ثانيةً **أنشأت مصدراً سادساً** — داخلَ
     * المربّع الذي بُني ليُنهي تعدُّدَ المصادر.
     *
     * وقد افترقت فعلاً قبل أن تُوصَل: «محطّةُ وقود» هنا، و«محطّة وقود»
     * في لوحة ٣٦٠، و«محطة وقود» في قائمة إنشاء الحساب. **فالتاجرُ
     * يُنشَأ باسمٍ ويُعرَض بآخر.**
     *
     * **والطويلُ والقصيرُ وجهان لمصدرٍ واحد:** الثابتُ يحمل الوصفَ
     * الكامل («بيع سريع (أسماك، خضار، بسطات)») لقائمة الاختيار، وهذه
     * تقتطع منه الاسمَ قبل القوس — لِترويسةٍ أو وسمٍ لا يتّسع للوصف.
     * فلا هجاءَ ثانياً يُكتب، ولا قائمةَ تشيخ.
     * ══════════════════════════════════════════════════════════════════
     */
    public function nameAr(): string
    {
        $label = A::BUSINESS_TYPE_LABELS[$this->code()] ?? $this->code();

        // ما قبل القوس: الوصفُ بين قوسين أمثلةٌ للمُختار لا اسمٌ للعرض.
        $short = trim((string) preg_replace('~\s*\(.*$~u', '', $label));

        return $short !== '' ? $short : $label;
    }

    /**
     * **نواةُ القطاع** — ما يخصّه وحدَه ولا يعمل بدونه.
     *
     * والمعيار: أزِلْ واحدةً، أيبقى القطاعُ قابلاً للاستعمال؟ فإن كان
     * الجوابُ «لا» فهي نواة. (طاولةٌ لا يُفتح عليها طلبٌ لا تبيع.)
     *
     * **ولا تُكتب هنا ميزةٌ من الصندوق المشترك.**
     *
     * @return array<int,string>
     */
    abstract public function own(): array;

    /**
     * **العمقُ المُباع** — ما تفتحه كلُّ باقةٍ فوق النواة.
     *
     * @return array<string,array<int,string>>  رمزُ الباقة ⇒ ميزاتُها
     */
    public function paidDepth(): array
    {
        return [];
    }

    // ══════════════════════════════════════════════════════════════════

    /**
     * ما يُمنح لهذا القطاع على باقةٍ بعينها: المشتركُ + نواتُه + عمقُ باقته.
     *
     * **والمجّانيّةُ لا عمقَ لها**: العمقُ هو ما يُباع، ومنحُه مجّاناً
     * يُفرغ الباقاتِ من معناها.
     *
     * @return array<int,string>
     */
    public function featuresFor(string $plan): array
    {
        return array_values(array_unique(
            array_merge(self::shared(), $this->own(), $this->depthFor($plan))));
    }

    /**
     * **عمقُ هذا القطاع الذي تبلغه هذه الباقةُ وحدَه.**
     *
     * وهي مدخلُ `AccessPresets::verticalPlanFeatures` — فصلٌ عن
     * `featuresFor` لأنّ `resolveFeatures` تجمع المصادرَ بنفسها، فلو
     * أعادت النواةَ والمشتركَ معها لَما تغيّر الاتّحادُ **لكنّ كلَّ مصدرٍ
     * صار يمنح كلَّ شيء** — ونزعُ ميزةٍ من موضعها يصير بلا أثر.
     *
     * @return array<int,string>
     */
    final public function depthFor(string $plan): array
    {
        // **والمجّانيّةُ لا عمقَ لها**: العمقُ هو ما يُباع، ومنحُه مجّاناً
        // يُفرغ الباقاتِ من معناها.
        if ($plan === A::PLAN_FREE) {
            return [];
        }

        $out = [];

        foreach ($this->paidDepth() as $atPlan => $features) {
            if ($this->planReaches($plan, $atPlan)) {
                $out = array_merge($out, $features);
            }
        }

        return array_values(array_unique($out));
    }

    /**
     * أتبلغ الباقةُ المشتراةُ الباقةَ المطلوبة؟
     *
     * **والترتيبُ يُقرأ من `ALL_PLANS`** — فباقةٌ تُضاف غداً تأخذ موضعَها
     * بلا تعديلٍ هنا. وسُلَّمٌ مكتوبٌ بيدٍ يشيخ مع أوّل قرارِ تسعير.
     */
    protected function planReaches(string $bought, string $required): bool
    {
        $order = A::ALL_PLANS;

        $b = array_search($bought, $order, true);
        $r = array_search($required, $order, true);

        return $b !== false && $r !== false && $b >= $r;
    }
}
