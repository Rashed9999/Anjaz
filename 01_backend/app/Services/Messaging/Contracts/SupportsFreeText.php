<?php

namespace App\Services\Messaging\Contracts;

/**
 * AMIAL-MESSAGING-001 — واجهةٌ منفصلةٌ للنصّ الحرّ.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولماذا لا تُدمج في `MessageProvider`؟**
 *
 * لأنّ مزوّدي الرسائل القصيرة الأربعة **لا يُرسلون نصّاً حرّاً** في هذا
 * المشروع — يُرسلون OTP وحده. فلو حُشر `sendText()` في العقد الأساسيّ
 * لاضطرّ كلٌّ منهم أن يُنفّذها بجسدٍ فارغٍ أو برميِ استثناء.
 *
 * وذاك بالضبط ما يمنعه مبدأ **Interface Segregation**: واجهةٌ كبيرةٌ
 * تُجبر من لا يحتاجها على تنفيذها، فتمتلئ الشيفرة بدوالَّ لا تفعل شيئاً —
 * وأخطرُ ما فيها أنّها **تُرجع بنجاحٍ كاذب**: يُستدعى `sendText` على
 * مزوّد SMS فلا يحدث شيء، ولا خطأ.
 *
 * فمن يُرسل نصّاً حرّاً يُعلنها، ومن لا يُرسل لا يُسأل عنها. ويفحص
 * المُرسِلُ `instanceof SupportsFreeText` — سؤالٌ يجيبه النظامُ لا تعليق.
 */
interface SupportsFreeText
{
    /**
     * يُرسل رسالةً نصّيّةً حرّة (إشعار/إيصال — لا OTP).
     *
     * ملاحظة: قوالبُ Meta و360dialog للنصّ الحرّ تتطلّب نافذةَ جلسةٍ
     * مدّتها ٢٤ ساعة؛ وخارجها قد تفشل وفق سياسة واتساب.
     *
     * @return bool نجح الإرسال فعلاً.
     */
    public function sendText(string $to, string $message): bool;
}
