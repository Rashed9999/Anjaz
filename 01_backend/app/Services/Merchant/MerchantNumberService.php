<?php

namespace App\Services\Merchant;

use App\Models\Merchant;
use RuntimeException;

/**
 * AMIAL-MERCHANT-NUMBER-001 — **رقمُ التاجر ستّةُ أرقامٍ عشوائيّة.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **الطلب:** «كان عبارةً عن أحرفٍ وأرقامٍ وشرطة… الآن أريده مكوَّناً من
 * ستّة أرقامٍ عشوائيّةٍ باستثناء الصفر».
 *
 * وقِيس ما كان: `sprintf('M-%05d', $user->id)` — أي `M-00042`. **وهو
 * مشتقٌّ من رقم المستخدم لا عشوائيّ**، وفي ذلك ثلاثةُ عيوبٍ لا واحد:
 *
 *   ① **يُفشي عدَّ التجّار.** من سجّل فرأى `M-00042` علم أنّه الثاني
 *      والأربعون. وهذا رقمٌ تجاريٌّ لا يُعطى لكلّ من سجّل.
 *   ② **ويُخمَّن.** `M-00041` و`M-00043` موجودان يقيناً، ورقمُ التاجر
 *      **عنوانُ دفعٍ يدفع إليه الزبائن** — لا معرّفٌ داخليّ.
 *   ③ ولا فرادةَ محروسةً في القاعدة، بل مضمونةٌ بالاشتقاق وحدَه — فأوّلُ
 *      مولِّدٍ لا يشتقّ يكسرها بصمت.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **ولا صفرَ في أيّ خانة** — قرارُ صاحب المشروع صراحةً. والمساحةُ إذن
 * ‏9⁶ = **٥٣١٬٤٤١** رقماً، لا مليون.
 *
 * **وهذا سقفٌ يُقال ولا يُسكت عنه:** التصادمُ يبدأ يكثر عند بضع مئاتٍ من
 * التجّار (مفارقةُ أعياد الميلاد)، والمولِّدُ يعيد المحاولة فيمتصّه. لكنّ
 * الاحتمالَ يرتفع مع النموّ، **فعند ٥٠٬٠٠٠ تاجرٍ تصير كلُّ محاولةٍ تاسعةٍ
 * تقريباً مصطدمة**. وحين يقترب المشروعُ من ذلك يُزاد رقمٌ سابع — وهو
 * تغييرُ ثابتٍ واحدٍ هنا لا إعادةُ بناء.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والفرادةُ تُحرَس في القاعدة لا في الشيفرة.**
 *
 * «اقرأ ثمّ اكتب» ليس ذرّيّاً: عمليّتان متزامنتان تقرآن الرقمَ نفسَه
 * فتجدانه حرّاً فتكتبانه. وهو الدرسُ الذي دُفع ثمنُه في هذا المشروع
 * مرّتين (`firstOrCreate` و`USER_WALLET_{id}`). **فقيدٌ فريدٌ في الجدول
 * هو الحارس**، والمحاولةُ تُعاد على تصادمه.
 *
 * **ورقمان متطابقان لتاجرين يعني أنّ زبوناً يدفع للخطأ منهما** — وهو
 * أسوأُ ما قد ينتج عن هذا الملفّ.
 *
 * ══════════════════════════════════════════════════════════════════════
 * **والقائمون لا يُرقَّمون** — قرارُ صاحب المشروع: «يبقون، والجديدُ
 * للجدد فقط». ورقمُ التاجر **بيانةُ دخولٍ وعنوانُ دفعٍ معاً**، فتغييرُه
 * على من لم يُبلَّغ يُقفله خارج حسابه ويُضيّع من يدفع إليه.
 *
 * يظهر في : التطبيق ← آخرُ خطوةٍ في التسجيل («رقم التاجر الخاص بك —
 * احفظه») · وشاشةُ الدخول · ولوحةُ التاجر. وفي لوحة الإدارة: مركزُ
 * التاجر وبطاقةُ الحساب. ويُوصل إليه من : التسجيلِ نفسِه، ومن إنشاء
 * حسابِ تاجرٍ من لوحة الإدارة.
 *
 * @see \Tests\Feature\MerchantNumberGuardTest
 */
class MerchantNumberService
{
    /** طولُ الرقم — ويُزاد واحداً حين تضيق المساحة. */
    public const LENGTH = 6;

    /**
     * الخاناتُ المسموحة — **بلا صفرٍ إطلاقاً**.
     *
     * ولها فائدةٌ ثانيةٌ لم تُطلَب: الصفرُ يُخلَط بحرف O حين يُملى
     * بالهاتف أو يُكتب بخطّ اليد على إيصال، وهذا رقمٌ يُملى كثيراً.
     */
    public const DIGITS = '123456789';

    /**
     * أقصى محاولاتٍ قبل الإقرار بالعجز.
     *
     * **والعجزُ يُرمى ولا يُبتلَع**: تاجرٌ بلا رقمٍ لا يستطيع الدخولَ
     * ولا يستطيع أحدٌ الدفعَ إليه، **فتسجيلٌ ينجح بلا رقمٍ أسوأ من
     * تسجيلٍ يفشل بسببٍ مفهوم**. (القاعدة السابعة.)
     */
    public const MAX_TRIES = 40;

    /**
     * **رقمٌ حرٌّ الآن** — ولا ضمانَ أنّه يبقى حرّاً حتّى تُحفظ الصفّ.
     *
     * فالفحصُ هنا يقلّل الاصطدام، **والقيدُ الفريدُ في القاعدة هو الذي
     * يمنعه**. ومن ينادي هذه الدالّةَ يلتقط تصادمَ الكتابة ويعيد النداء
     * — و`assignTo()` تفعل ذلك عنه.
     */
    public function generate(): string
    {
        for ($i = 0; $i < self::MAX_TRIES; $i++) {
            $candidate = $this->random();

            if (! Merchant::where('merchant_number', $candidate)->exists()) {
                return $candidate;
            }
        }

        throw new RuntimeException(
            'تعذّر توليدُ رقم تاجرٍ حرٍّ بعد '.self::MAX_TRIES.' محاولة — '
            .'المساحةُ ('.self::LENGTH.' أرقامٍ بلا صفر) تضيق. '
            .'زِد `MerchantNumberService::LENGTH` رقماً واحداً.');
    }

    /**
     * يمنح المتجرَ رقماً ويحفظه، **مُعيداً المحاولةَ على تصادم الكتابة**.
     *
     * وهذا هو البابُ الذي يُنادى — لا `generate()` وحدَها: بينها وبين
     * الحفظ نافذةٌ يسبق فيها غيرُك.
     */
    public function assignTo(Merchant $merchant): string
    {
        for ($i = 0; $i < self::MAX_TRIES; $i++) {
            $number = $this->generate();

            try {
                $merchant->merchant_number = $number;
                $merchant->save();

                return $number;
            } catch (\Illuminate\Database\UniqueConstraintViolationException) {
                // سبقني غيري إلى الرقم نفسِه بين الفحص والحفظ — وهذا
                // **بالضبط ما يحرسه القيدُ الفريد**. تُعاد المحاولة.
                continue;
            }
        }

        throw new RuntimeException(
            'تعذّر حفظُ رقم تاجرٍ فريدٍ بعد '.self::MAX_TRIES.' محاولة.');
    }

    /**
     * **عشوائيٌّ آمنٌ تشفيريّاً** — لا `rand()`.
     *
     * ورقمُ التاجر عنوانُ دفعٍ يُخمَّن ثمنُ تخمينه مال، ومولِّدٌ متوقَّعُ
     * البذرة يُعيد العيبَ الذي وُلد هذا الملفُّ لإصلاحه بثوبٍ آخر.
     *
     * **و`protected` لا `private` عمداً**: حارسُ نفادِ المساحة كان مسحاً
     * نصّيّاً يبحث عن `throw` في الملفّ — **فمرّ وأنا أكسره**، لأنّ في
     * الملفّ رميتين وأنا نزعتُ واحدة. (القاعدة الثانية: حارسٌ لم يسقط
     * ليس حارساً.) فصار يُجرَّب بالسلوك: صنفٌ يرث ويُثبّت المخرَج،
     * فيُقاس النفادُ حقّاً بدل أن يُقرأ نصّاً.
     */
    protected function random(): string
    {
        $out = '';
        $max = strlen(self::DIGITS) - 1;

        for ($i = 0; $i < self::LENGTH; $i++) {
            $out .= self::DIGITS[random_int(0, $max)];
        }

        return $out;
    }
}
