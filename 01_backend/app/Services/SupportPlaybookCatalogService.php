    /**
     * البحث في موسوعة الـ 100 سؤال مصرفي مع التصفية حسب القسم أو نمط تحريك الحساب.
     *
     * @return array<int,array<string,mixed>>
     */
    public function searchTop100(?string $query = null, ?string $category = null, ?string $actionMode = null): array
    {
        $rows = collect($this->top100Catalog());

        if ($category !== null && $category !== '') {
            $rows = $rows->where('category', $category);
        }

        if ($actionMode !== null && $actionMode !== '') {
            $rows = $rows->where('action_mode', $actionMode);
        }

        $needle = trim(mb_strtolower((string) $query));
        if ($needle === '') {
            return $rows->values()->all();
        }

        return $rows->map(function (array $row) use ($needle) {
            $haystack = mb_strtolower(implode(' ', array_filter([
                $row['question'],
                $row['category'],
                $row['domain_ar'] ?? '',
                $row['diagnosis'],
                $row['escalation'],
                $row['account_movement'] ?? '',
                implode(' ', $row['keywords']),
                implode(' ', $row['steps']),
            ])));

            $score = 0;
            foreach (preg_split('/\s+/u', $needle) ?: [] as $token) {
                $token = trim($token);
                if (mb_strlen($token) < 2) continue;
                if (str_contains($haystack, $token)) $score += 2;
                if (str_contains(mb_strtolower($row['question']), $token)) $score += 3;
            }

            $row['_score'] = $score;
            return $row;
        })
        ->filter(fn (array $row) => $row['_score'] > 0)
        ->sortByDesc('_score')
        ->map(function (array $row) {
            unset($row['_score']);
            return $row;
        })
        ->values()
        ->all();
    }

    /**
     * إحصاءات جاهزية دعم أميال باي على الـ 100 سؤال مصرفي.
