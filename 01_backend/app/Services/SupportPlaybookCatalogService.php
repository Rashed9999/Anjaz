    /** @return array<int,array<string,mixed>> */
    public function search(?string $query = null, ?string $category = null): array
    {
        $rows = collect($this->all());

        if ($category !== null && $category !== '') {
            $rows = $rows->where('category', $category);
        }

        $needle = trim(mb_strtolower((string) $query));
        if ($needle === '') {
            return $rows->values()->all();
        }

        return $rows->map(function (array $row) use ($needle) {
            $haystack = mb_strtolower(implode(' ', array_filter([
                $row['question'],
                $row['category'],
                $row['diagnosis'],
                $row['escalation'],
                implode(' ', $row['keywords']),
                implode(' ', $row['steps']),
            ])));

            $score = 0;
            foreach (preg_split('/\s+/u', $needle) ?: [] as $token) {
                $token = trim($token);
                if (mb_strlen($token) < 2) continue;
                if (str_contains($haystack, $token)) $score += 2;
                if (str_contains(mb_strtolower($row['question']), $token)) $score += 3;
            }

            $row['_score'] = $score;
            return $row;
        })
        ->filter(fn (array $row) => $row['_score'] > 0)
        ->sortByDesc('_score')
        ->map(function (array $row) {
            unset($row['_score']);
            return $row;
        })
        ->values()
        ->all();
    }

