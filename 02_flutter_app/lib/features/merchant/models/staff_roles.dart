/// AMIAL-STAFF-ROLES-001 — **وظائفُ الموظّفين: سؤالٌ واحدٌ مكانَ خمسة.**
///
/// ══════════════════════════════════════════════════════════════════════
/// **الثمنُ الذي قِيس:** شاشةُ «موظف جديد» كانت تسأل خمسةَ أسئلةٍ عن كلّ
/// موظّف — يبيع؟ يُرجع؟ منتجات؟ تقارير؟ آجل؟ **وهي أسئلةُ مهندسٍ لا
/// صاحبِ محلّ.** والتاجرُ يفكّر «هذا كاشير»، لا «هذا مَن `sell` له
/// و`refund` عنه».
///
/// **ولا يُنزَع شيء:** الخادمُ ما زال يُنفّذ بالصلاحيّات نفسِها،
/// و[roleCustom] يفتح المربّعاتِ الخمسةَ كاملةً. فالسهولةُ افتراضٌ لا
/// سقف.
///
/// ══════════════════════════════════════════════════════════════════════
/// **ولمَ ملفٌّ مستقلّ:** كانت الخرائطُ `static const` خاصّةً داخل
/// الشاشة، **فلا يبلغها اختبار** — وحارسٌ لا يُنفَّذ ليس حارساً. فصارت
/// هنا، ويحرسها `test/features/merchant/staff_roles_test.dart`.
class StaffRoles {
  const StaffRoles._();

  /// مفتاحُ «مخصّص» — لا صلاحيّاتِ له في [permissions] عمداً: هو الوحيدُ
  /// الذي يفتح المربّعات.
  static const String custom = 'custom';

  /// كلُّ صلاحيّةٍ يقبلها الخادم — والمرجعُ الذي تُقاس عليه الأدوار.
  static const Map<String, String> allPermissions = {
    'sell': 'البيع',
    'refund': 'المرتجعات',
    'products': 'المنتجات',
    'reports': 'التقارير',
    'credit': 'الآجل',
  };

  /// ما يظهر في القائمة، بترتيبه.
  static const Map<String, String> labels = {
    'cashier': 'كاشير',
    'shift': 'مدير مناوبة',
    'manager': 'مدير',
    custom: 'مخصّص…',
  };

  /// ما يستطيعه الدورُ بكلامٍ يُقرأ تحت القائمة — لا برموزٍ إنجليزيّة.
  static const Map<String, String> says = {
    'cashier': 'يبيع فقط',
    'shift': 'يبيع · يُرجع · يبيع بالآجل',
    'manager': 'كلُّ شيء — ومنه التقارير والمنتجات',
    custom: 'اختر بنفسك',
  };

  /// **والترتيبُ تصاعديٌّ عمداً:** كاشير ⊂ مناوبة ⊂ مدير. فترقيةُ موظّفٍ
  /// لا تنزع عنه قدرةً كان يملكها — وهو عطلٌ أمسكه حارسُ الباقات من قبل.
  static const Map<String, Set<String>> permissions = {
    'cashier': {'sell'},
    'shift': {'sell', 'refund', 'credit'},
    'manager': {'sell', 'refund', 'products', 'reports', 'credit'},
  };

  /// الدورُ الافتراضيّ — وهو نفسُ ما كانت عليه الشاشة (`{'sell'}`)، فمن
  /// ضغط «إنشاء» بلا قراءةٍ يحصل على ما كان يحصل عليه بالضبط.
  static const String defaultRole = 'cashier';

  /// الأدوارُ المرتّبةُ من الأضيق إلى الأوسع — يقرؤها الحارس.
  static const List<String> ladder = ['cashier', 'shift', 'manager'];
}
