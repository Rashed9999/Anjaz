import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:uuid/uuid.dart';

/// AMIAL-POS-DEVICES-009 — **هويّةُ تثبيتٍ مستقرّة، لا تتبُّعُ عتاد.**
///
/// ══════════════════════════════════════════════════════════════════════
/// **القيدُ السادس من صاحب المشروع حرفاً:**
///
///   «لا تثق بـdevice UUID قادم من Flutter كدليل أمان وحيد. عرّف بوضوح
///    مصدره وسلوكه عند إعادة التثبيت/مسح البيانات/تبديل الجهاز. استخدم
///    هوية تثبيت مستقرة مخزّنة بشكل آمن، بدون تتبّع عتاد غير ضروري.»
///
/// ══════════════════════════════════════════════════════════════════════
/// **المصدرُ يُقال ولا يُخمَّن:**
///
/// معرِّفٌ عشوائيٌّ (v4) يُولَّد **مرّةً واحدة** ويُثبَّت في المخزن الآمن
/// (Keychain على iOS · EncryptedSharedPreferences على أندرويد). **ولا
/// يُشتقّ من رقمٍ تسلسليٍّ ولا IMEI ولا معرِّف إعلانات** — فتلك تتبُّعُ
/// حاملٍ لا هويّةُ مقعد، وبعضُها يُرفض في المتاجر أصلاً.
///
/// **وسلوكُه في الحالات الثلاث معلومٌ ومقبول:**
///
///   إعادةُ تثبيت التطبيق  → قد يتغيّر (‏أندرويد يمسح المخزن أحياناً)
///   مسحُ بيانات التطبيق   → **يتغيّر يقيناً**
///   تبديلُ الجهاز          → يتغيّر يقيناً
///
/// وفي الحالات الثلاث يظهر «جهازٌ جديد» فيستهلك مقعداً. **والعلاجُ من
/// شاشة الإدارة**: يُلغي التاجرُ المقعدَ القديم فيُفرَج عنه — لا بمحاولة
/// تتبُّعٍ أعمق تكسر الخصوصيّة وتُخطئ أيضاً.
///
/// **والخادمُ لا يثق بهذا وحدَه**: يُجزّئه بسرٍّ لا يعرفه التطبيق، ويربط
/// الرمزَ بالمقعد في جدولٍ عنده — فحذفُ الترويسة أو تزويرُها لا يُحرّر
/// رمزاً من مقعده. (‏انظر `PosDeviceSession` في الخادم.)
class PosDeviceIdentity {
  PosDeviceIdentity._();

  static const _key = 'amial_pos_device_uuid';

  static const _storage = FlutterSecureStorage(
    aOptions: AndroidOptions(encryptedSharedPreferences: true),
    iOptions: IOSOptions(accessibility: KeychainAccessibility.first_unlock),
  );

  /// يُقرأ من الذاكرة بعد أوّل نداء — فالمخزنُ الآمن بطيءٌ نسبيّاً.
  static String? _cached;

  /// **المعرِّفُ — يُولَّد مرّةً ويُثبَّت.**
  ///
  /// وأيُّ فشلٍ في المخزن يُعيد `null` **ولا يُخترَع معرِّفٌ عابر**:
  /// معرِّفٌ يتغيّر كلَّ تشغيلٍ يستهلك مقعداً جديداً في كلّ مرّة، فيُحرق
  /// حدُّ التاجر في يوم. **والصمتُ أسلمُ من هويّةٍ كاذبة.**
  static Future<String?> get() async {
    if (_cached != null) return _cached;

    try {
      final existing = await _storage.read(key: _key);

      if (existing != null && existing.length >= 8) {
        _cached = existing;
        return _cached;
      }

      final fresh = const Uuid().v4();
      await _storage.write(key: _key, value: fresh);
      _cached = fresh;

      return _cached;
    } catch (_) {
      return null;
    }
  }

  /// **يُنسى المعرِّفُ محلّيّاً** — لتسليم الجهاز أو اختباره.
  ///
  /// ولا يُلغي المقعدَ في الخادم: الإلغاءُ فعلُ التاجر من شاشته، وجعلُه
  /// تلقائيّاً هنا يجعل مسحَ بياناتِ تطبيقٍ يُطفئ مقعداً يعمل عليه غيرُه.
  static Future<void> forget() async {
    _cached = null;

    try {
      await _storage.delete(key: _key);
    } catch (_) {
      // لا شيء — النسيانُ المحلّيُّ ليس عمليّةً حرجة.
    }
  }
}
