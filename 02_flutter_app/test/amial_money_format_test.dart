import 'package:flutter_test/flutter_test.dart';

import 'package:amial_pay/helper/amial_money.dart';

/// AMIAL-MONEY-002 — عرض المبالغ: آخر خطوة قبل عين المستخدم.
///
/// **لماذا كان هذا الملفّ ناقصاً:**
/// `AmialMoney` تمرّ عليها كل قيمة مالية تُعرض في التطبيق — الرصيد، ومبلغ
/// التحويل، وشاشة التأكيد، والإيصال. ولم يكن عليها اختبار واحد.
///
/// وخللٌ هنا لا يُوقف شيئاً ولا يُنتج عطلاً يُبلَّغ عنه: الحوالة تنجح،
/// والمبلغ الصحيح يُخصم، والرقم المعروض وحده خاطئ. فيرى المستخدم رصيداً
/// ليس رصيده، أو يؤكّد مبلغاً غير الذي سيُخصم. لا شيء ينهار — تنهار الثقة.
///
/// والخادم يُرجع المبالغ نصّاً بأربع خانات ("1500.0000")، فالتحويل إلى شكل
/// بشريّ ليس تجميلاً بل ترجمة، وأي ترجمة تحتمل الخطأ.
void main() {
  group('ما يردّه الخادم فعلاً', () {
    test('أربع خانات عشرية تُعرض عدداً صحيحاً', () {
      // هذا الشكل بعينه هو ما يصل من كل نقاط النهاية المالية.
      expect(AmialMoney.fmt('1500.0000'), '1,500');
      expect(AmialMoney.fmt('600.0000'), '600');
      expect(AmialMoney.fmt('0.0000'), '0');
    });

    test('الكسر الحقيقي يبقى، والأصفار الزائدة تُحذف', () {
      expect(AmialMoney.fmt('1234.5000'), '1,234.5');
      expect(AmialMoney.fmt('1234.5600'), '1,234.56');
    });

    test('فواصل الآلاف في كل المراتب', () {
      expect(AmialMoney.fmt('1000'), '1,000');
      expect(AmialMoney.fmt('999'), '999');
      expect(AmialMoney.fmt('1234567'), '1,234,567');
      // مبالغ الجملة والتسويات تبلغ هذا الحدّ، فالفاصلة هي ما يجعلها تُقرأ.
      expect(AmialMoney.fmt('250000000'), '250,000,000');
    });
  });

  group('القيم التي تُسقط العرض لو أُهملت', () {
    test('null وفارغ يُعرضان صفراً لا استثناءً', () {
      // حقل مبلغ غائب من استجابة ناقصة يجب أن يعرض 0، لا أن يُسقط الشاشة.
      expect(AmialMoney.fmt(null), '0');
      expect(AmialMoney.fmt(''), '0');
      expect(AmialMoney.fmt('   '), '0');
    });

    test('نصّ غير رقمي يُعاد كما هو ولا يُرمى', () {
      expect(AmialMoney.fmt('غير محدد'), 'غير محدد');
    });

    test('الأنواع الرقمية تُقبل كما تُقبل النصوص', () {
      // بعض النقاط تردّ رقماً وبعضها نصّاً — والشاشة واحدة.
      expect(AmialMoney.fmt(1500), '1,500');
      expect(AmialMoney.fmt(1500.5), '1,500.5');
    });
  });

  group('السالب — الاسترداد والخصم', () {
    test('الإشارة تبقى والفاصلة في موضعها', () {
      // يظهر في كشف الحساب: كل خصم سطر سالب.
      expect(AmialMoney.fmt('-1500.0000'), '-1,500');
      expect(AmialMoney.fmt('-999'), '-999');
    });
  });

  group('رمز العملة', () {
    test('يُلحق بعد الرقم لا قبله', () {
      // العربية تكتب «600 ر.ي». وضعه قبل الرقم يجعله يبدو جزءاً منه.
      expect(AmialMoney.yer('600.0000'), '600 ر.ي');
      expect(AmialMoney.yer('1234567'), '1,234,567 ر.ي');
    });
  });

  group('حدود التقريب', () {
    test('يُقرّب إلى خانتين ولا يبتر', () {
      // البتر يُنقص المعروض عن الحقيقي دائماً، والتقريب يوزّع الفرق.
      expect(AmialMoney.fmt('1234.567'), '1,234.57');
      expect(AmialMoney.fmt('0.005'), '0.01');
    });

    test('كسر أصغر من نصف قرش يظهر صفراً لا فراغاً', () {
      expect(AmialMoney.fmt('0.001'), '0');
    });
  });
}
