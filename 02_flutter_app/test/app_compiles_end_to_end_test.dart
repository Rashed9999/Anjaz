// ══════════════════════════════════════════════════════════════════════
// AMIAL-BUILD-LOCK-001 — **التطبيقُ كلُّه يُصرَّف، بتبعيّاته.**
//
// **الثمن:** سقط بناءُ Codemagic على حزمةٍ لا نملكها:
//
//     flutter_html-3.0.0/lib/src/tree/styled_element.dart:31:17:
//     Error: Method not found: 'matches'.
//
// والبوّابةُ المحلّيّةُ كانت خضراءَ تماماً: طبقةُ «تصريف Dart» تشغّل
// `flutter analyze`، **وهو لا يمسّ مصادرَ الحزم في `.pub-cache`
// إطلاقاً** — يحلّل شيفرتَنا وحدَها. فكسرٌ داخل تبعيّةٍ يمرّ صامتاً،
// وأوّلُ من يقرؤه Codemagic بعد ثلاث دقائق بناء.
//
// ══════════════════════════════════════════════════════════════════════
// **وهذا الملفُّ يُصرِّف الشجرةَ كلَّها بسطرِ استيرادٍ واحد.**
//
// استيرادُ `main.dart` يجرّ كلَّ ما يستورده التطبيقُ فعلاً — شاشاتِه
// وخدماتِه **وكلَّ حزمةٍ يعتمد عليها**. و`flutter test` يبني نواةً
// (kernel) قبل التشغيل، وهي الخطوةُ نفسُها التي سقطت في Codemagic
// (`Target kernel_snapshot_program failed`).
//
// **ولا يُشغَّل `main()`** — الاستيرادُ لا يُنفّذ، فلا Firebase ولا شبكة
// ولا حالةٌ تُبنى. المقصودُ التصريفُ لا التشغيل.
//
// **ولمَ لا يكفي `flutter analyze`:** المحلِّلُ يقرأ **الواجهاتِ**
// المُعلَنة، والمُصرِّفُ يقرأ **الأجسام**. ودالّةٌ مفقودةٌ في جسم حزمةٍ
// خارجيّةٍ لا يراها الأوّلُ ويسقط عليها الثاني — وهو بعينه ما وقع.
// ══════════════════════════════════════════════════════════════════════

import 'package:amial_pay/main.dart' as app;
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('التطبيقُ وتبعيّاتُه تُصرَّف — فسقوطُ التصريف يقع هنا لا في Codemagic', () {
    // **الوصولُ إلى الرمز يُثبت أنّ الوحدةَ صُرِّفت وحُمِّلت.**
    //
    // ولا يُكتفى بالاستيراد: مُصرِّفٌ كسولٌ قد يؤجّل ما لا يُمَسّ، فيمرّ
    // ملفٌّ يستورد ولا يقرأ. ولمسُ `main` يُلزم التحميل.
    expect(app.main, isNotNull,
        reason: 'تعذّر تحميلُ نقطة الدخول — والرسالةُ أعلاه هي رسالةُ '
            'المُصرِّف نفسِها التي كان سيطبعها Codemagic.');
  });
}
