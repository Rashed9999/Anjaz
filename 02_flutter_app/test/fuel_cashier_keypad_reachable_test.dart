import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// AMIAL-FUEL-KEYPAD-001 — **لوحةُ الأرقام مبنيّةٌ ويُوصَل إليها.**
///
/// ══════════════════════════════════════════════════════════════════════
/// **قاله صاحبُ المشروع:** «شاشةُ بيع الوقود كانت تحتوي على لوحة أرقام،
/// الآن اختفت — أعدها».
///
/// وقِيس فلم تُحذف: `FuelCashierScreen` (تصميم #103) قائمةٌ كاملةً
/// بلوحتها وأزرارها السريعة وتبديلِ «بالريال/باللتر». **لكنّ لا سطرَ
/// واحداً في التطبيق كلِّه كان يفتحها** — صفرُ مراجع.
///
/// وهو نمطُ العطل الأكثر تكراراً في هذا المشروع: **مبنيٌّ ولا يُوصَل
/// إليه**. ولا يمسكه مُصرِّفٌ ولا `flutter analyze`: الشاشةُ صحيحةٌ
/// نحويّاً وتُصرَّف، وغيابُها من الدرج ليس خطأً في أيّ أداة.
///
/// ══════════════════════════════════════════════════════════════════════
/// **وثلاثةُ أشياءَ تُحرَس معاً، لأنّ كلَّ واحدٍ منها كافٍ لإعادة العطل:**
///
///   ① أن تبقى اللوحةُ في الشاشة (لا تُبسَّط إلى حقلِ نصّ).
///   ② أن يفتحها بابٌ من درج التاجر.
///   ③ أن تبقى الشاشةُ المطوّلةُ موصولةً كذلك — فهي وحدَها تحمل
///      **بطاقةَ الشركة والبيعَ الآجل**، واستبدالُها باللوحة يُعيد
///      لوحةً ويُسقط طريقتَي دفع.
void main() {
  final cashier = File(
      'lib/features/fuel_station/screens/fuel_cashier_screen.dart');
  final shell = File(
      'lib/features/merchant/screens/merchant_adaptive_shell.dart');

  test('الملفّان في مكانهما — وإلّا فحصنا العدم', () {
    expect(cashier.existsSync(), isTrue,
        reason: 'شاشةُ كاشير المحطّة غير موجودة');
    expect(shell.existsSync(), isTrue, reason: 'درجُ التاجر غير موجود');
  });

  test('اللوحةُ الرقميّةُ ما زالت في شاشة الكاشير', () {
    final src = cashier.readAsStringSync();

    expect(src.contains('keypad'), isTrue,
        reason: 'لوحةُ الأرقام اختفت من شاشة الكاشير — '
            'وهي ما طلب صاحبُ المشروع إعادتَه بالاسم.');
  });

  test('ودرجُ التاجر يفتحها — فشاشةٌ لا يُوصل إليها ليست مبنيّة', () {
    final src = shell.readAsStringSync();

    // ══════════════════════════════════════════════════════════════
    // **ويُقاس البناءُ لا ذكرُ الاسم.**
    //
    // جُرّب هذا بالعكس فمرّ: نُزع استعمالُ الشاشة من الدرج **وبقي
    // سطرُ الاستيراد**، فوجد الفحصُ الاسمَ وقال «لها باب». أي أنّه كان
    // يحرس `import` لا وجهةَ زرّ.
    // ══════════════════════════════════════════════════════════════
    expect(src.contains('const FuelCashierScreen()'), isTrue,
        reason: 'لا بابَ إلى لوحة الأرقام من درج التاجر. '
            'وهي مبنيّةٌ كاملةً — فتُصرَّف ولا تُفتح، ولا يقول ذلك '
            'مُصرِّفٌ ولا محلِّل.');
  });

  test('والشاشةُ المطوّلةُ تبقى — فيها وحدَها الآجل وبطاقة الشركة', () {
    final shellSrc = shell.readAsStringSync();
    final saleSrc = File(
        'lib/features/fuel_station/screens/fuel_sale_screen.dart')
        .readAsStringSync();

    expect(shellSrc.contains('const FuelSaleScreen()'), isTrue,
        reason: 'سقط بابُ الشاشة المطوّلة — ومعه البيعُ الآجل وبطاقةُ '
            'الشركة، وهما مبنيّان ولا بديلَ لهما في اللوحة.');

    for (final method in ['company_card', 'credit']) {
      expect(saleSrc.contains(method), isTrue,
          reason: 'طريقةُ الدفع «$method» اختفت من الشاشة المطوّلة — '
              'فلا موضعَ لها في التطبيق إطلاقاً.');
    }
  });

  test('ولا يعود الشحنُ المباشرُ بهاتف العميل', () {
    final src = cashier.readAsStringSync();

    // الخادمُ يردّ: «دفع الوقود يتم عبر QR يؤكده العميل بنفسه».
    // فزرٌّ يرسل `customer_phone` مع `amial_pay` يُردّ ٤٢٢ دائماً —
    // ويُربك موظّفَ المحطّة بلا سببٍ ظاهر.
    expect(src.contains("'customer_phone'"), isFalse,
        reason: 'عاد الشحنُ المباشرُ بهاتف العميل إلى كاشير المحطّة — '
            'وهو ما شُدّد في الخادم: الدفعُ بـQR يؤكّده العميلُ بنفسه.');
  });
}
