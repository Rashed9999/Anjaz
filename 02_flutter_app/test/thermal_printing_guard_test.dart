import 'dart:io';
import 'dart:typed_data';

import 'package:amial_pay/features/printer/services/thermal_print_service.dart';
import 'package:flutter_test/flutter_test.dart';

/// AMIAL-PRINT-GUARD-001 — **طبقةُ الطباعة كانت بلا حارسٍ واحد.**
///
/// ══════════════════════════════════════════════════════════════════════
/// **ما قِيس قبل هذا الملفّ:**
///
///   · في الخادم **أربعةَ عشرَ حارساً** للإيصالات — أرقامُها وتنزيلُها
///     وسلامتُها ووزنُها وصفحةُ التحقّق العامّة.
///   · وفي التطبيق: `lib/features/printer/` **تسعُمئةٍ وثمانيةَ عشرَ
///     سطراً**، فيها توليدُ بايتات ESC/POS ونبضةُ درج النقد — **وصفرُ
///     اختبار**.
///
/// والفرقُ ليس إهمالاً بل بنية: الطبقةُ تنتهي عند جهاز، فيُقال «لا
/// تُختبَر إلّا بطابعة». **وهذا صحيحٌ في الإرسال وخطأٌ في التوليد**:
/// البايتاتُ دالّةٌ صافية — صورةٌ داخلةٌ وأوامرُ خارجة، ولا جهازَ في
/// الطريق. فكُشفت `buildRaster` وقِيست.
///
/// ══════════════════════════════════════════════════════════════════════
/// **وما يحرسه ليس شكلاً بل ثلاثةُ أشياءَ تُرى في الدنيا:**
///
///   ① **درجُ النقد** — `ESC p` أمرٌ يفتح دُرجَ مالٍ حقيقيّاً. سقوطُه
///     صامت (يُفتح باليد)، **وظهورُه حيث لا يُطلَب أخطر**: دُرجٌ ينفتح
///     مع كلّ إيصالٍ في وجه الزبون.
///   ② **القطع** — بلا `GS V` يخرج الإيصالُ متّصلاً بالذي بعده.
///   ③ **العرض** — ٥٨ملّم و٨٠ملّم مقاسان مختلفان، والخلطُ بينهما
///     يقصّ نصفَ الإيصال أو يطبعه في ثلث الورقة.
void main() {
  late ThermalPrintService svc;

  setUp(() => svc = ThermalPrintService());

  /// صورةُ RGBA سوداءُ معتمة — كلُّ بِتٍّ يجب أن يُضيء.
  ///
  /// **والألفا ٢٥٥ لا صفر**: أوّلُ صياغةٍ كتبتُها ملأت البايتاتِ كلَّها
  /// أصفاراً فصارت **شفّافةً لا سوداء**، فقرأها المحوِّلُ بيضاءَ بحقّ —
  /// وسقط الفحصُ على تجهيزٍ خاطئٍ لا على عطل. (والحارسُ الذي يسقط على
  /// حالةٍ لم يصنعها يُطارَد فيه ما لا وجودَ له.)
  Uint8List black(int w, int h) {
    final b = Uint8List(w * h * 4);
    for (var i = 3; i < b.length; i += 4) {
      b[i] = 255; // ألفا معتمة، وRGB تبقى صفراً = أسود
    }
    return b;
  }

  /// صورةٌ بيضاءُ شفّافة — لا بِتَّ يُضيء.
  Uint8List white(int w, int h) {
    final b = Uint8List(w * h * 4);
    for (var i = 0; i < b.length; i++) {
      b[i] = 255;
    }
    return b;
  }

  // ═══════════════════════════════════════════════════════════════════

  /// **① الإيصالُ يبدأ بتهيئةٍ وينتهي بقطع.**
  test('أوامرُ الإيصال كاملةٌ: تهيئةٌ وصورةٌ وتغذيةٌ وقطع', () {
    final out = svc.buildRaster(white(8, 8), 8, 8, openCashDrawer: false);

    expect(out.take(2).toList(), [0x1B, 0x40],
        reason: '**لا تهيئةَ في أوّل الإيصال** (`ESC @`) — فتبقى إعداداتُ '
            'الطباعة السابقةُ من إيصالٍ ماضٍ: خطٌّ عريضٌ أو محاذاةٌ '
            'غريبةٌ تنتقل إلى ما بعدها.');

    expect(out.sublist(out.length - 3), [0x1D, 0x56, 0x01],
        reason: '**لا أمرَ قطعٍ في آخره** (`GS V 1`) — فيخرج الإيصالُ '
            'متّصلاً بالذي بعده، ويُسلَّم الزبونُ إيصالَ غيره معه.');

    expect(out.join(','), contains('27,100,3'),
        reason: 'سقطت التغذيةُ (`ESC d 3`) — فيُقطَع الورقُ على السطر '
            'الأخير ويُبتَر.');

    // GS v 0 — رأسُ الصورة النقطيّة.
    expect(out.join(','), contains('29,118,48,0'),
        reason: '**لا صورةَ في الإيصال** — سقط `GS v 0`، فيخرج ورقٌ '
            'أبيضُ وأوامرُ قطعٍ ولا شيءَ مطبوع.');
  });

  /// **② ونبضةُ الدرج تُرسَل حين تُطلَب وحدَها.**
  ///
  /// ══════════════════════════════════════════════════════════════════
  /// وهي **الحالةُ التي تُرى في الدنيا لا في السجلّ**: لا خطأَ يُكتب
  /// في الحالتين، والفرقُ دُرجٌ ينفتح أو لا ينفتح أمام الزبون.
  /// (القاعدة التاسعة: يُقاس أثرُ الضغطة لا غيابُ الخطأ.)
  /// ══════════════════════════════════════════════════════════════════
  group('نبضةُ درج النقد', () {
    // ESC p m t1 t2 — النبضةُ القياسيّة.
    const pulse = '27,112,0,25,250';

    test('تُرسَل حين يفعّلها التاجر', () {
      final out = svc.buildRaster(white(8, 8), 8, 8, openCashDrawer: true);

      expect(out.join(','), contains(pulse),
          reason: '**فُعِّل درجُ النقد ولم تُرسَل نبضتُه** — فيبقى الدرجُ '
              'مقفلاً ويفتحه الكاشيرُ بيده مع كلّ عمليّة، ولا سطرَ '
              'خطأٍ في أيّ سجلّ.');
    });

    test('ولا تُرسَل حين لا يفعّلها', () {
      final out = svc.buildRaster(white(8, 8), 8, 8, openCashDrawer: false);

      expect(out.join(','), isNot(contains(pulse)),
          reason: '**نبضةُ الدرج تُرسَل بلا طلب** — فينفتح دُرجُ المال '
              'مع كلّ إيصالٍ في وجه الزبون. وهذا أخطرُ من ألّا ينفتح.');
    });

    test('وتقع قبل القطع لا بعده', () {
      final out = svc.buildRaster(white(8, 8), 8, 8, openCashDrawer: true);
      final s = out.join(',');

      expect(s.indexOf(pulse), lessThan(s.indexOf('29,86,1')),
          reason: 'النبضةُ بعد أمر القطع — وبعضُ الطابعات تُنهي المهمّة '
              'عند القطع فلا يصل ما بعده.');
    });
  });

  /// **③ والعرضُ يتبع مقاسَ الورق.**
  test('عرضُ الصورة يُحسب بالبايت لا بالبكسل', () {
    // ٥٧٦ نقطةً = ٨٠ملّم ⇒ ٧٢ بايتاً في السطر.
    final wide = svc.buildRaster(white(576, 4), 576, 4, openCashDrawer: false);
    // ٣٨٤ نقطةً = ٥٨ملّم ⇒ ٤٨ بايتاً.
    final narrow = svc.buildRaster(white(384, 4), 384, 4, openCashDrawer: false);

    expect(wide.join(','), contains('29,118,48,0,72,0'),
        reason: '**عرضُ ٨٠ملّم ليس ٧٢ بايتاً** — والطابعةُ تقرأ الرأسَ '
            'حرفيّاً، فتُزاح الصورةُ أو تُقصّ.');

    expect(narrow.join(','), contains('29,118,48,0,48,0'),
        reason: '**عرضُ ٥٨ملّم ليس ٤٨ بايتاً** — فيُطبَع إيصالُ البقّالة '
            'في ثلث الورقة أو يُقصّ نصفُه.');

    expect(wide.length, greaterThan(narrow.length),
        reason: 'الورقُ الأعرضُ لا يُنتج بايتاتٍ أكثر — فالعرضُ لا يُقرأ '
            'أصلاً.');
  });

  /// **④ والأسودُ يُطبَع والأبيضُ لا.**
  ///
  /// فمُحوِّلٌ مقلوبٌ يُخرج ورقةً سوداءَ كاملة — يستهلك الحبرَ والورق
  /// ولا يُقرأ منه حرف.
  test('الأسودُ بِتٌّ مضيءٌ والأبيضُ مطفأ', () {
    const w = 8, h = 1;

    final blackOut = svc.buildRaster(black(w, h), w, h, openCashDrawer: false);
    final whiteOut = svc.buildRaster(white(w, h), w, h, openCashDrawer: false);

    // بايتُ الصفّ يقع بعد رأس `GS v 0` بثمانية بايتات.
    int rowByte(List<int> out) {
      final i = out.join(',').indexOf('29,118,48,0');
      final tail = out.sublist(
          out.length - 3 /* القطع */ - 3 /* التغذية */ - 1);
      expect(i, isNot(-1));

      return tail.first;
    }

    expect(rowByte(blackOut), 0xFF,
        reason: '**الأسودُ لم يُضِئ بِتّاً** — فتخرج الورقةُ بيضاءَ '
            'والإيصالُ مفقود، ولا خطأَ في أيّ سجلّ.');

    expect(rowByte(whiteOut), 0x00,
        reason: '**الأبيضُ أضاء بِتّاً** — فتخرج ورقةٌ سوداءُ كاملةً '
            'تستهلك الحبرَ ولا تُقرأ.');
  });

  /// **⑤ والشفّافُ يُقرأ أبيضَ لا أسود.**
  ///
  /// فخلفيّةُ الإيصال شفّافةٌ حين يُلتقط الـwidget، ولو قُرئت سوداءَ
  /// لخرجت كلُّ ورقةٍ سوداء.
  test('الشفّافُ ورقٌ أبيضُ لا حبرٌ أسود', () {
    const w = 8, h = 1;
    final transparent = Uint8List(w * h * 4); // ألفا = 0

    final out = svc.buildRaster(transparent, w, h, openCashDrawer: false);
    final tail = out.sublist(out.length - 7);

    expect(tail.first, 0x00,
        reason: '**الشفّافُ قُرئ حبراً** — وخلفيّةُ الإيصال شفّافةٌ عند '
            'الالتقاط، فتخرج كلُّ ورقةٍ سوداءَ كاملة.');
  });

  /// **⑥ ورسالةُ الفشل تقول أيَّ فشلٍ هو.**
  ///
  /// ══════════════════════════════════════════════════════════════════
  /// كانت `catch (_)` واحدةٌ تُخرج «حدث خطأ أثناء الطباعة» لسبعة
  /// أسباب. **والكاشيرُ واقفٌ والزبونُ ينتظر**، فلا يعرف أيفحص السلك أم
  /// الشبكة أم الرقم. ومهارةُ الطباعة تشترط التمييزَ نصّاً ولكلٍّ رمزُه.
  /// ══════════════════════════════════════════════════════════════════
  group('رسالةُ فشل الشبكة', () {
    String say(SocketException e) => svc.sayNetworkForTest(e, '192.168.1.50', 9100);

    test('المنفذُ مرفوض ⇒ طابعةٌ مطفأةٌ أو منفذٌ خطأ', () {
      final m = say(const SocketException('failed',
          osError: OSError('Connection refused', 111)));

      expect(m, contains('PRINT_1000'));
      expect(m, contains('مطفأة'),
          reason: 'الرفضُ يعني جهازاً موجوداً لا يسمع — وهو أشهرُ '
              'أسباب الفشل، فلا يُخلَط بانقطاع الشبكة.');
    });

    test('لا شبكة ⇒ يُقال الواي‑فاي', () {
      final m = say(const SocketException('failed',
          osError: OSError('Network is unreachable', 101)));

      expect(m, contains('PRINT_1001'));
      expect(m, contains('واي'));
    });

    test('لا ردّ ⇒ مهلةٌ لا رفض', () {
      final m = say(const SocketException('timeout'));

      expect(m, contains('PRINT_1005'));
    });

    test('وكلُّ رسالةٍ تحمل العنوانَ والمنفذ', () {
      for (final e in [
        const SocketException('t'),
        const SocketException('r', osError: OSError('Connection refused', 111)),
        const SocketException('u', osError: OSError('Network is unreachable', 101)),
      ]) {
        expect(say(e), contains('192.168.1.50'),
            reason: '**رسالةٌ بلا عنوان لا تُصلَّح** — والكاشيرُ يقارنها '
                'بورقةٍ ملصقةٍ على الطابعة.');
      }
    });

    test('وما لا يُعرف يُقال خاماً ولا يُخترَع له سبب', () {
      final m = say(const SocketException('x',
          osError: OSError('Some unheard-of failure', 999)));

      expect(m, contains('PRINT_1007'));
      expect(m, contains('Some unheard-of failure'),
          reason: '**سببٌ مجهولٌ اختفى من الرسالة** — وترجمةٌ مخترَعةٌ '
              'تُمرّر القارئَ واثقاً من معنىً لم يقصده أحد. '
              '(القاعدة السابعة.)');
    });
  });
}
